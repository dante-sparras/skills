@unittest.skipUnless(shutil.which("node"), "Node is not installed")
class Factory(unittest.TestCase):
    @classmethod
    def setUpClass(cls):
        done = subprocess.run(
            ["node", str(HARNESS), str(FACTORY), json.dumps(CASES)], capture_output=True, text=True, cwd=REPO
        )
        if done.returncode:
            raise AssertionError(f"factory.ts did not load under the harness:\n{done.stderr}")
        out = json.loads(done.stdout.strip().splitlines()[-1])
        cls.registered = out["registered"]
        results = iter(out["results"])
        cls.blockers = [next(results) for _ in BLOCKERS]
        cls.numbers = [next(results) for _ in range(2)]
        cls.parents = [next(results) for _ in PARENTS]
        cls.keys = [next(results) for _ in REPEAT_KEYS]
        cls.feedback = [next(results) for _ in FEEDBACK]
        cls.briefs = [next(results) for _ in range(2)]
        cls.failing = [next(results) for _ in FAILING]
        cls.titles = [next(results) for _ in TITLES]
        cls.search = next(results)
        cls.pairs = [next(results) for _ in ROLE_PAIRS]
        cls.unasked = [next(results) for _ in UNASKED]

    def test_registers_every_workflow(self):
        # The factory skill, factory.md and the factory's own `start` calls name these. Rename them together.
        self.assertEqual(self.registered, ["skills-factory-ship", "skills-factory-spec", "skills-factory-dispatch"])

    def test_finds_blockers_in_an_issue_body(self):
        for (body, want), got in zip(BLOCKERS, self.blockers):
            with self.subTest(body=body):
                self.assertEqual(got, want)

    def test_issue_number_drops_the_hash(self):
        self.assertEqual(self.numbers, ["526", "526"])

    def test_finds_a_tickets_parent_spec(self):
        for (body, want), got in zip(PARENTS, self.parents):
            with self.subTest(body=body):
                self.assertEqual(got, want)

    def test_one_friction_has_one_key_however_it_is_written(self):
        for (args, want), got in zip(REPEAT_KEYS, self.keys):
            with self.subTest(target=args[2]):
                self.assertEqual(got, want)

    def test_hears_collaborators_and_only_them(self):
        for (name, _, want), got in zip(FEEDBACK, self.feedback):
            with self.subTest(name):
                ids = {key: [said["id"] for said in got[key]] for key in ["fresh", "outside"]}
                self.assertEqual({"held": got["held"], **ids}, want)

    def test_a_guardrail_brief_is_an_agent_brief_the_factory_can_build(self):
        two, one = self.briefs
        self.assertTrue(two.startswith(MARKER))
        for line in ["**Route:** change", "`correct`", "2 runs", "Searched 4 folders", "PR https://x/pull/2", "`docs/`: No index"]:
            with self.subTest(line=line):
                self.assertIn(line, two)
        self.assertIn("A run of the skills factory", one)
        self.assertNotIn("seen once", one)


    def test_a_role_comes_from_the_roles_files(self):
        for (name, _, want), got in zip(ROLE_PAIRS, self.pairs):
            with self.subTest(name):
                self.assertEqual(got, want)

    def test_merges_unasked_only_when_the_repo_allows_it_and_the_door_is_two_way(self):
        for (config, verdict, want), got in zip(UNASKED, self.unasked):
            with self.subTest(config=config, verdict=verdict):
                self.assertEqual(got, want)

    def test_main_is_red_only_on_a_finished_failure(self):
        for (name, _, _, want), got in zip(FAILING, self.failing):
            with self.subTest(name):
                self.assertEqual([check["name"] for check in got], want)

    def test_the_same_follow_up_has_the_same_title_key(self):
        for (title, want), got in zip(TITLES, self.titles):
            with self.subTest(title=title):
                self.assertEqual(got, want)

    def test_a_search_takes_eight_plain_words(self):
        self.assertEqual(self.search, "rename the db client it is used in")


if __name__ == "__main__":
    unittest.main()

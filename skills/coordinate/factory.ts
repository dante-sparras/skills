const issueNumber = (issue) => String(issue.displayKey).replace(/^#/, "");

/** Issue numbers named in a `Blocked by` line or section of an issue body. */
const blockersInBody = (body) => {
  const found = new Set();
  const lines = String(body ?? "").split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const inline = /^\s*\**blocked by\**:?\s*(.*)$/i.exec(lines[i]);
    const heading = /^#{1,6}\s*blocked by\s*$/i.test(lines[i]);
    if (!inline && !heading) continue;
    let text = inline ? inline[1] : "";
    // A section runs until the next heading.
    for (let j = i + 1; heading && j < lines.length && !/^#{1,6}\s/.test(lines[j]); j++) text += ` ${lines[j]}`;
    for (const match of text.matchAll(/#(\d+)/g)) found.add(match[1]);
  }
  return [...found];
};

/** The issue number in a ticket's `## Parent` section, as to-spec-and-tickets writes it, or null. */
const parentInBody = (body) => {
  const lines = String(body ?? "").split(/\r?\n/);
  const at = lines.findIndex((line) => /^#{1,6}\s*parent\s*$/i.test(line));
  if (at < 0) return null;
  for (let j = at + 1; j < lines.length && !/^#{1,6}\s/.test(lines[j]); j++) {
    const match = /(?:#|\/issues\/)(\d+)/.exec(lines[j]);
    if (match) return match[1];
  }
  return null;
};

/** The store key of one friction: its kind and its target, written one way. */
const repeatKey = (repository, kind, target) => {
  const where = String(target)
    .trim()
    .replace(/^`+|`+$/g, "")
    .replace(/\\/g, "/")
    .replace(/^\.\//, "")
    .replace(/\/+$/, "")
    .replace(/\s+/g, " ")
    .toLowerCase();
  return `${PREFIX}/repeats/${repository}/${kind}/${where}`;
};

const cut = (text, max) => (text.length > max ? `${text.slice(0, max - 3)}...` : text);
const isAgentPost = (item) => String(item.body ?? "").trimStart().startsWith("> *This was generated by AI");

/**
 * What collaborators said on a PR that the run has not handled yet, and who holds the PR: each
 * collaborator whose latest review asks for changes. Reviews come oldest first, as GitHub lists
 * them. An agent's post carries the AI marker, so it never counts, whichever account posted it.
 */
const feedbackOf = ({ reviews, comments, lineComments, handled }) => {
  const byCollaborator = (item) => COLLABORATORS.includes(item.author_association) && !isAgentPost(item);
  const latest = new Map();
  for (const review of reviews.filter(byCollaborator)) {
    if (["APPROVED", "CHANGES_REQUESTED", "DISMISSED"].includes(review.state)) latest.set(review.login, review.state);
  }
  const said = [
    ...reviews
      .filter(byCollaborator)
      .filter((review) => review.state === "CHANGES_REQUESTED" || (review.state !== "APPROVED" && String(review.body ?? "").trim() !== ""))
      .map((review) => ({ id: `review-${review.id}`, author: review.login, url: review.html_url, text: `${review.state}: ${review.body ?? ""}` })),
    ...comments.filter(byCollaborator).map((c) => ({ id: `comment-${c.id}`, author: c.login, url: c.html_url, text: c.body ?? "" })),
    ...lineComments.filter(byCollaborator).map((c) => ({ id: `line-${c.id}`, author: c.login, url: c.html_url, text: c.body ?? "" })),
  ];
  return {
    held: [...latest].filter(([, state]) => state === "CHANGES_REQUESTED").map(([login]) => login),
    fresh: said.filter((item) => !handled.includes(item.id)).map((item) => ({ ...item, text: cut(item.text.trim(), 600) })),
  };
};


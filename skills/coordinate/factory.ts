/** An agent on the role's default model, then once more on its backup when the first attempt fails. */
const hire = Effect.fn(function* (name, options, pair) {
  const first = yield* agent.try(name, pair ? { ...options, model: pair.default } : options);
  if (first.outcome === "done") return first;
  const earlier = first.thread ? ` Its thread is ${first.thread.threadId}. Continue its branch and PR if it left any.` : "";
  const fallback = pair ? { model: pair.backup ?? pair.default } : {};
  return yield* agent.try(`${name}-again`, {
    ...options,
    ...fallback,
    brief: `${options.brief}\n\nAn earlier attempt at this failed: ${first.reason}.${earlier}`,
  });
});

/**
 * Count one friction against every earlier run. When it reaches its count, file a guardrail
 * issue in ready-for-agent, so the factory builds the fix. A friction already filed adds a comment.
 */
const countRepeat = Effect.fn(function* (config, name, seen) {
  const key = repeatKey(config.repository, seen.kind, seen.target);
  const entry = store.entry(key, Repeat);
  const sighting = { run: seen.run, task: seen.task, thread: seen.thread, pr: seen.pr, detail: seen.detail };
  const counted = yield* step(
    name,
    { returns: Repeat },
    entry
      .update((found) => {
        const earlier = Option.isSome(found) ? found.value : { kind: seen.kind, target: seen.target, sightings: [], filed: null };
        return { ...earlier, sightings: [...earlier.sightings, sighting] };
      })
      .pipe(Effect.map((next) => Option.getOrThrow(next))),
  );
  if (counted.filed !== null) {
    yield* step(
      `${name}-seen-again`,
      { returns: Schema.Void },
      issues.comment(issueAddress(config, counted.filed), `${AI_MARKER}\n\nSeen again:\n\n${sightingLine(sighting)}`),
    );
    return;
  }
  if (counted.sightings.length < (seen.kind === "broken" ? 1 : REPEAT_AFTER)) return;
  const singles = yield* step(
    `${name}-singles`,
    { returns: Schema.Array(Repeat) },
    store
      .entries(`${PREFIX}/repeats/${config.repository}/${seen.kind}/`, Repeat)
      .pipe(Effect.map((rows) => rows.filter((row) => row.key !== key && row.value.filed === null && row.value.sightings.length === 1).map((row) => row.value))),
  );
  const labels = labelsOf(config);
  const url = yield* step(
    `${name}-file`,
    { returns: Schema.String },
    createIssue(config, `Guardrail: ${seen.kind} at ${counted.target}`, guardrailBrief(counted, singles), [labels.ready, labels.enhancement]),
  );
  yield* step(
    `${name}-filed`,
    { returns: Schema.Void },
    entry.update((found) => (Option.isSome(found) ? { ...found.value, filed: url } : undefined)).pipe(Effect.asVoid),
  );
});

/** What a run collects from its agents, and how it files that when the run ends. */
const ledgerOf = (config, run, task) => {
  const followUps = [];
  const sightings = [];
  const keep = (result, where) => {
    followUps.push(...result.followUps);
    for (const item of [...result.friction, ...(result.checkable ?? [])]) {
      sightings.push({ ...item, run: run.id, task, thread: where.thread ?? null, pr: where.pr ?? null });
    }
  };
  /** File the follow-ups, count the friction, and leave a note on the task when there is one. */
  const wrapUp = Effect.fn(function* (note) {
    for (const [i, line] of followUps.entries()) {
      yield* step(
        `follow-up-${i + 1}`,
        { returns: Schema.Void },
        issues
          .create({
            project: config.project,
            title: cut(line, 80),
            body: `${AI_MARKER}\n\n${line}\n\nCame up while the skills factory worked on ${task}.`,
            labels: [config.needsTriageLabel],
          })
          .pipe(Effect.asVoid),
      );
    }
    for (const [i, seen] of sightings.entries()) yield* countRepeat(config, `friction-${i + 1}`, seen);
    if (note) yield* step("note", { returns: Schema.Void }, issues.comment(issueAddress(config, task), `${AI_MARKER}\n\n${note}`));
  });
  return { keep, wrapUp };
};

/**
 * After a ticket's PR merged: close the ticket if the merge did not, and when it was its spec's
 * last open ticket, start the spec's check. A spec gets one check: once the gaps that check filed
 * have landed too, the spec closes.
 */
const afterMerge = (config, issue) =>
  Effect.gen(function* () {
    const repo = config.repository;
    const cwd = config.project;
    const ticket = JSON.parse(yield* gh(["api", `repos/${repo}/issues/${issue.number}`], cwd));
    if (ticket.state === "open") yield* gh(["issue", "close", issue.number, "--repo", repo, "--comment", `${AI_MARKER}\n\nIts PR merged.`], cwd);
    const parent = yield* gh(["api", `repos/${repo}/issues/${issue.number}/parent`, "--jq", ".number"], cwd).pipe(
      Effect.map((out) => out.trim() || parentInBody(ticket.body)),
      Effect.orElseSucceed(() => parentInBody(ticket.body)),
    );
    if (!parent) return "no spec";
    const spec = JSON.parse(yield* gh(["api", `repos/${repo}/issues/${parent}`], cwd));
    if (spec.state !== "open" || !spec.labels.some((label) => label.name === labelsOf(config).spec)) return `#${parent} is not an open spec`;
    const states = (yield* gh(["api", "--paginate", `repos/${repo}/issues/${parent}/sub_issues`, "--jq", ".[].state"], cwd)).split(/\s+/).filter(Boolean);
    if (states.length === 0 || states.some((state) => state !== "closed")) return `spec #${parent} has open tickets`;
    const key = `spec/${repo}/${parent}`;
    // A prefix match would take spec 123's runs for spec 12's, so keep the exact key only.
    const earlier = (yield* runs({ workflow: specCheck, keyPrefix: key })).filter((r) => r.key === key);
    if (earlier.some((r) => ACTIVE.includes(r.status))) return `the check of spec #${parent} is still running`;
    if (earlier.some((r) => r.status === "completed")) {
      yield* gh(
        ["issue", "close", parent, "--repo", repo, "--comment", `${AI_MARKER}\n\nEvery ticket of this spec has landed, and so has each gap its spec check found.`],
        cwd,
      );
      return `closed spec #${parent}`;
    }
    if (earlier.length > 0) return `the check of spec #${parent} ended without a result. Its run says why`;
    yield* start(specCheck, { config, spec: { number: String(parent), displayKey: `#${parent}`, title: spec.title, url: spec.html_url } }, { key });
    return `started the check of spec #${parent}`;
  });

const ship = workflow(
  "skills-factory-ship",
  {
    version: 3,
    payload: ShipInput,
    // The issue leaves the queue however the run ends, unless the run parked it to wait on
    // another issue. A person adds the label back to retry.
    onEnd: (input, end) =>
      Effect.gen(function* () {
        const parked = yield* store.entry(resumeKey(input.config, input.issue), Resume).get;
        if (end.outcome === "stopped" && Option.isSome(parked)) return;
        yield* gh(
          ["issue", "edit", input.issue.number, "--repo", input.config.repository, "--remove-label", input.config.readyLabel],
          input.config.project,
        );
      }),
  },
  Effect.fn(function* (input, run) {
    const { config, issue } = input;
    yield* title(`${issue.displayKey} ${issue.title}`);
    const ledger = ledgerOf(config, run, issue.url);

    /** End the run as stopped, and tell the issue why and how to try again. */
    const halt = Effect.fn(function* (reason) {
      yield* ledger.wrapUp(
        `The skills factory stopped on this issue: ${reason}\n\nIt removed \`${config.readyLabel}\`. Add the label back to try again. Run \`${run.id}\` in T3 Code holds the details.`,
      );
      return yield* stop(reason);
    });

    const resumed = yield* step(
      "resume",
      { returns: Schema.NullOr(Resume) },
      Effect.gen(function* () {
        const entry = store.entry(resumeKey(config, issue), Resume);
        const found = yield* entry.get;
        if (Option.isNone(found)) return null;
        yield* entry.delete;
        return found.value;
      }),
    );
    const verifySkill = yield* step("verify-skill", { returns: Schema.NullOr(Schema.String) }, findVerifySkill(config));

    // ---- The worker builds the issue.
    const worker = yield* hire(
      "worker",
      {
        project: config.project,
        issue: issueAddress(config, issue.url),
        workspace: worktreeOf(config),
        title: `Worker: ${issue.displayKey} ${issue.title}`,
        brief: workerBrief(input, verifySkill, resumed),
        returns: WorkerResult,
        quiet: "2 hours",
        timeout: "24 hours",
      },
      config.worker,
    );
    if (worker.outcome === "failed") return yield* halt(`the worker failed twice: ${worker.reason}`);
    const workerThread = worker.thread;
    let result = worker.value;
    ledger.keep(result, { thread: workerThread.threadId, pr: result.pr });

    // ---- A missing verify skill parks the issue behind a new issue that creates it.
    if (result.status === "BLOCKED" && result.blockedOn === "verify-skill") {
      const labels = labelsOf(config);
      const verifyIssue = yield* step(
        "verify-skill-issue",
        { returns: Schema.String },
        Effect.gen(function* () {
          // One issue per repo: the first run that needs it files it, and the rest wait on it.
          const entry = store.entry(`${PREFIX}/verify-skill/${config.repository}`, Schema.String);
          const known = yield* entry.get;
          if (Option.isSome(known)) {
            const state = (yield* gh(["issue", "view", known.value, "--repo", config.repository, "--json", "state", "--jq", ".state"], config.project)).trim();
            if (state === "OPEN") return known.value;
          }
          const url = yield* createIssue(
            config,
            "Create this repo's verify skill",
            [
              AI_MARKER,
              "",
              "## Agent Brief",
              "",
              "**Category:** enhancement",
              "**Route:** change",
              "**Summary:** Create this repo's verify skill with the `create-verify-skill` skill.",
              "",
              "**Current behavior:**",
              `The repo has no verify skill, so a worker could not prove its change on the running app: ${issue.url}.`,
              "",
              "**Desired behavior:**",
              "A `verify-<app>` skill under `.claude/skills/` that launches the app, drives it, and captures evidence.",
              "",
              "**Acceptance criteria:**",
              "- [ ] A fresh agent ran the skill cold and passed, as `create-verify-skill` says",
            ].join("\n"),
            [labels.ready, labels.enhancement],
          );
          yield* entry.set(url);
          return url;
        }),
      );
      const blocker = verifyIssue.split("/").pop();
      const linked = yield* step.try(
        "wait-on-verify-skill",
        { returns: Schema.Void },
        Effect.gen(function* () {
          const id = (yield* gh(["api", `repos/${config.repository}/issues/${blocker}`, "--jq", ".id"], config.project)).trim();
          yield* gh(["api", "--method", "POST", `repos/${config.repository}/issues/${issue.number}/dependencies/blocked_by`, "-F", `issue_id=${id}`], config.project);
        }),
      );
      if (linked.outcome === "failed") {
        // Without native dependencies, a `Blocked by` line holds it back just the same.
        yield* step(
          "wait-on-verify-skill-line",
          { returns: Schema.Void },
          Effect.gen(function* () {
            const body = (yield* gh(["issue", "view", issue.number, "--repo", config.repository, "--json", "body", "--jq", ".body"], config.project)).trimEnd();
            yield* gh(["issue", "edit", issue.number, "--repo", config.repository, "--body", `Blocked by: #${blocker}\n\n${body}`], config.project);
          }),
        );
      }
      yield* step("park", { returns: Schema.Void }, store.entry(resumeKey(config, issue), Resume).set({ pr: result.pr, thread: workerThread.threadId }));
      yield* ledger.wrapUp(
        `The skills factory parked this issue until ${verifyIssue} lands, since proving it needs a verify skill. It keeps \`${config.readyLabel}\`, and the factory takes it up again once that issue closes.`,
      );
      return yield* stop(`waiting on ${verifyIssue}`);
    }

    if (result.status !== "DONE") return yield* halt(`the worker returned ${result.status}: ${result.summary}`);
    if (result.pr === null) {
      yield* ledger.wrapUp(`The skills factory finished this issue without a PR.\n\n${result.summary}`);
      return { summary: result.summary };
    }

    // ---- The PR's path: green checks, collaborators heard, a review of the current head, then
    // a person's go to merge.
    const pr = issueAddress(config, result.pr);
    let verdict = null; // { headSha, comment, approved }
    let rulings = "none";
    let rounds = 0;
    const handled = []; // Ids of collaborator comments the worker has been given.
    let goAhead = false; // The user said to merge over a collaborator's request for changes.
    let holding = 0; // Checks so far on a collaborator who asked for changes.

    /** Wake the worker on its own thread, and take what it returns. */
    const wake = Effect.fn(function* (name, what) {
      rounds++;
      const woken = yield* agent.try(name, { thread: workerThread, brief: wokeBrief(what), returns: WorkerResult, quiet: "2 hours", timeout: "12 hours" });
      if (woken.outcome === "failed") return yield* halt(`the worker failed after it was woken: ${woken.reason}`);
      ledger.keep(woken.value, { thread: workerThread.threadId, pr: pr.url });
      if (woken.value.status !== "DONE") return yield* halt(`the worker returned ${woken.value.status}: ${woken.value.summary}`);
      return woken.value;
    });

    /** End the run on a merge, whoever made it. */
    const landed = Effect.fn(function* (how) {
      const next = yield* step.try("after-merge", { returns: Schema.String }, afterMerge(config, issue));
      yield* ledger.wrapUp(next.outcome === "failed" ? `The PR merged, but the factory could not check its spec: ${next.reason}` : null);
      return { pr: pr.url, merged: how };
    });

    for (let pass = 1; ; pass++) {
      if (rounds >= MAX_ROUNDS) return yield* halt(`${pr.url} went round fixes and review ${MAX_ROUNDS} times without landing.`);
      const at = yield* pullRequests.wait(`checks-${pass}`, pr, { until: "checks", timeout: "3 hours" });
      if (Option.isNone(at)) return yield* halt(`the checks on ${pr.url} were still running after 3 hours.`);
      const standing = at.value;
      if (standing.state === "merged") return yield* landed("outside the factory");
      if (standing.state === "closed") return yield* halt(`${pr.url} was closed outside the factory.`);
      if (standing.checks === "failing" || standing.mergeability === "conflicting") {
        const what = standing.checks === "failing" ? "a check fails on your PR." : "your PR conflicts with main.";
        result = yield* wake(`fix-${pass}`, `${what} PR: ${pr.url}.`);
        continue;
      }

      // A collaborator's comment goes to the worker before anything else, as a request to weigh.
      const said = yield* step(`feedback-${pass}`, { returns: Feedback }, readFeedback(config, pr.url, handled));
      if (said.fresh.length > 0) {
        handled.push(...said.fresh.map((item) => item.id));
        const list = said.fresh.map((item) => `- ${item.author} (${item.url}): ${item.text}`).join("\n");
        result = yield* wake(
          `feedback-${pass}-fix`,
          `collaborators commented on ${pr.url}. Weigh each one as rules.md says, answer it on the PR, and push what you change.\n\n${list}\n\n`,
        );
        continue;
      }

      const head = yield* step(
        `head-${pass}`,
        { returns: Schema.String },
        pullRequests.read(pr).pipe(Effect.map((detail) => detail.headSha ?? "")),
      );

      if (verdict === null || verdict.headSha !== head) {
        rounds++;
        const review = yield* hire(
          `review-${pass}`,
          {
            project: config.project,
            workspace: worktreeOf(config),
            title: `Reviewer: ${issue.displayKey} ${issue.title}`,
            brief: reviewerBrief(input, verifySkill, pr.url, workerThread.threadId, verdict?.comment ?? "none", rulings),
            returns: Verdict,
            timeout: "8 hours",
          },
          config.reviewer,
        );
        if (review.outcome === "failed") return yield* halt(`the reviewer failed twice: ${review.reason}`);
        ledger.keep(review.value, { thread: review.thread?.threadId, pr: pr.url });
        const v = review.value;
        if (v.status === "FAILED" || v.headSha === null) return yield* halt(`the reviewer could not reach a verdict: ${v.summary}`);
        if (v.status === "PASS") {
          verdict = { headSha: v.headSha, comment: v.comment, approved: false };
          continue; // Back to the checks, now at the head the verdict names.
        }
        const ruling = yield* ask(`ruling-${pass}`, {
          title: `${issue.displayKey}: the reviewer and the worker disagree on ${pr.url}`,
          choices: ["land it as it is", "send my rulings to the worker", "stop"],
          data: { pr: pr.url, head: v.headSha, verdict: v.comment, open: v.open },
          timeout: "7 days",
        });
        if (Option.isNone(ruling)) return yield* halt("nobody ruled on the open findings within 7 days.");
        if (ruling.value.choice === "stop") return yield* halt("the user stopped it at the ruling.");
        if (ruling.value.choice === "land it as it is") {
          verdict = { headSha: v.headSha, comment: v.comment, approved: true };
          continue;
        }
        rulings = ruling.value.reason?.trim() || "The user sided with the reviewer on every open finding.";
        verdict = { headSha: v.headSha, comment: v.comment, approved: false };
        result = yield* wake(`rulings-${pass}`, `the user ruled on the reviewer's open findings on ${pr.url}: ${rulings}`);
        continue;
      }

      // A collaborator's request for changes holds the PR until they approve or the user says go.
      if (said.held.length > 0 && !goAhead) {
        if (holding === 0) {
          const hold = yield* ask(`hold-${pass}`, {
            title: `${issue.displayKey}: ${said.held.join(", ")} asked for changes on ${pr.url}`,
            choices: ["wait for their approval", "merge without it", "stop"],
            data: { pr: pr.url, head, held: said.held, verdict: verdict.comment },
            timeout: "7 days",
          });
          if (Option.isNone(hold)) return yield* halt(`nobody answered within 7 days whether to wait for ${said.held.join(", ")}.`);
          if (hold.value.choice === "stop") return yield* halt("the user stopped it while a collaborator held it.");
          if (hold.value.choice === "merge without it") goAhead = true;
        }
        if (!goAhead) {
          holding++;
          if (holding > MAX_HOLD_CHECKS) return yield* halt(`${said.held.join(", ")} still asked for changes on ${pr.url} after 7 days.`);
          yield* sleep(`held-${pass}`, HOLD_CHECK);
          continue;
        }
      }

      // Checks are green at the head the verdict covers, and no collaborator holds it.
      let go = verdict.approved || goAhead;
      if (!go) {
        const answer = yield* ask(`merge-${pass}`, {
          title: `${issue.displayKey}: merge ${pr.url}?`,
          choices: ["merge", "I will merge it", "stop"],
          data: { pr: pr.url, head, verdict: verdict.comment, summary: result.summary },
          timeout: "7 days",
        });
        if (Option.isNone(answer)) return yield* halt("nobody answered the merge question within 7 days.");
        if (answer.value.choice === "stop") return yield* halt("the user stopped it before the merge.");
        if (answer.value.choice === "I will merge it") {
          const merged = yield* pullRequests.wait(`merged-${pass}`, pr, { until: "merged", timeout: "14 days" });
          if (Option.isNone(merged) || merged.value.state !== "merged") {
            return yield* halt(`${pr.url} was not merged within 14 days, or was closed.`);
          }
          return yield* landed("by the user");
        }
        go = true;
      }

      // `--match-head-commit` makes GitHub refuse the merge if the head moved since the review.
      const merge = yield* step.try(
        `merge-${pass}`,
        { returns: Schema.Void },
        gh(["pr", "merge", pr.url, `--${config.mergeMethod}`, "--match-head-commit", head], config.project).pipe(Effect.asVoid),
      );
      if (merge.outcome === "failed") {
        const now = yield* step(
          `head-after-merge-${pass}`,
          { returns: Schema.String },
          pullRequests.read(pr).pipe(Effect.map((detail) => detail.headSha ?? "")),
        );
        if (now !== head) continue; // The head moved, so it goes back through checks and review.
        return yield* halt(`the merge of ${pr.url} failed: ${merge.reason}`);
      }
      yield* step.try(`delete-branch-${pass}`, { returns: Schema.Void }, pullRequests.act(pr, "delete-branch"));
      return yield* landed(head);
    }
  }),
);

/** The check of a spec whose tickets have all landed: a reviewer proves its user stories on main. */
const specCheck = workflow(
  "skills-factory-spec",
  { version: 1, payload: SpecInput },
  Effect.fn(function* (input, run) {
    const { config, spec } = input;
    yield* title(`Spec check: ${spec.displayKey} ${spec.title}`);
    const ledger = ledgerOf(config, run, spec.url);
    const labels = labelsOf(config);
    const verifySkill = yield* step("verify-skill", { returns: Schema.NullOr(Schema.String) }, findVerifySkill(config));

    const check = yield* hire(
      "reviewer",
      {
        project: config.project,
        workspace: worktreeOf(config),
        title: `Spec check: ${spec.displayKey} ${spec.title}`,
        brief: specBrief(input, verifySkill),
        returns: SpecResult,
        timeout: "8 hours",
      },
      config.reviewer,
    );
    if (check.outcome === "failed") {
      yield* ledger.wrapUp(`The skills factory could not check this spec: the reviewer failed twice: ${check.reason}`);
      return yield* stop(`the reviewer failed twice: ${check.reason}`);
    }
    const v = check.value;
    ledger.keep(v, { thread: check.thread?.threadId, pr: null });
    if (v.status === "FAILED") {
      yield* ledger.wrapUp(`The skills factory could not check this spec: ${v.summary}`);
      return yield* stop(`the spec check failed: ${v.summary}`);
    }
    if (v.status === "PASS") {
      yield* ledger.wrapUp(null);
      yield* step("close-spec", { returns: Schema.Void }, gh(["issue", "close", spec.number, "--repo", config.repository], config.project).pipe(Effect.asVoid));
      return { spec: spec.url, result: "PASS", sha: v.sha };
    }

    // Each gap becomes a ticket of the spec, which the factory builds like any other.
    const filed = [];
    for (const [i, gap] of v.gaps.entries()) {
      const url = yield* step(
        `gap-${i + 1}`,
        { returns: Schema.String },
        createIssue(
          config,
          gap.title,
          [
            AI_MARKER,
            "",
            "## Parent",
            "",
            `#${spec.number}`,
            "",
            "## What to build",
            "",
            `This user story fails on main: ${gap.story}`,
            "",
            "## Acceptance criteria",
            "",
            "- [ ] The story holds on main, proven on the real surface",
            "",
            "## Evidence",
            "",
            gap.evidence,
            "",
            "## Blocked by",
            "",
            "None",
          ].join("\n"),
          [labels.ready, labels.bug],
        ),
      );
      filed.push(url);
      yield* step.try(
        `gap-${i + 1}-link`,
        { returns: Schema.Void },
        Effect.gen(function* () {
          const id = (yield* gh(["api", `repos/${config.repository}/issues/${url.split("/").pop()}`, "--jq", ".id"], config.project)).trim();
          yield* gh(["api", "--method", "POST", `repos/${config.repository}/issues/${spec.number}/sub_issues`, "-F", `sub_issue_id=${id}`], config.project);
        }),
      );
    }
    yield* ledger.wrapUp(
      `The spec check found ${filed.length} gap(s), each filed as a ticket of this spec:\n\n${filed.map((url) => `- ${url}`).join("\n")}\n\nThe spec closes once they land.`,
    );
    return { spec: spec.url, result: "GAPS", gaps: filed };
  }),
);

workflow(
  "skills-factory-dispatch",
  { version: 1, payload: Tick, triggers: [every("10 minutes")] },
  Effect.fn(function* () {
    const started = yield* step(
      "dispatch",
      { returns: Schema.Array(Schema.String) },
      Effect.gen(function* () {
        const projects = yield* store.entries(`${PREFIX}/projects/`, Config);
        const earlier = yield* runs({ workflow: ship });
        const keys = [];
        for (const { value: config } of projects) {
          if (!config.enabled) continue;
          const own = `ship/${config.repository}/`;
          let room = config.maxActive - earlier.filter((r) => r.key?.startsWith(own) && ACTIVE.includes(r.status)).length;
          if (room <= 0) continue;
          const ready = yield* issues.list({ project: config.project, labels: [config.readyLabel], limit: 100 });
          // Oldest first, so nothing waits behind newer work for long.
          const queue = [...ready].sort((a, b) => String(a.createdAt).localeCompare(String(b.createdAt)));
          for (const issue of queue) {
            if (room <= 0) break;
            const number = issueNumber(issue);
            const prefix = `${own}${number}/`;
            const tries = earlier.filter((r) => r.key?.startsWith(prefix));
            if (tries.some((r) => ACTIVE.includes(r.status))) continue;
            if ((yield* openBlockers(config, number)) > 0) continue;
            // A new key per try: a key already used gives back the run that has it.
            const key = `${prefix}${tries.length + 1}`;
            yield* start(ship, { config, issue: { number, displayKey: issue.displayKey, title: issue.title, url: issue.url } }, { key });
            keys.push(key);
            room--;
          }
        }
        return keys;
      }),
    );
    if (started.length === 0) return yield* skip("no issue to start");
    return started;
  }),
);

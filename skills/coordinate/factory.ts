/** The body of a guardrail issue: an agent brief the factory's worker builds with add-guardrail. */
const guardrailBrief = (repeat, singles) =>
  [
    AI_MARKER,
    "",
    "## Agent Brief",
    "",
    "**Category:** enhancement",
    "**Route:** change",
    `**Summary:** Agents keep hitting the same ${repeat.kind} friction at \`${repeat.target}\`. Run the \`add-guardrail\` skill on it.`,
    "",
    "**Current behavior:**",
    `${repeat.sightings.length === 1 ? "A run" : `${repeat.sightings.length} runs`} of the skills factory hit this:`,
    "",
    ...repeat.sightings.map(sightingLine),
    "",
    "**Desired behavior:**",
    "The next agent cannot make this mistake, or a check fails and its error names the fix. Fix it at the highest level `add-guardrail` allows.",
    "",
    "**Acceptance criteria:**",
    "- [ ] The PR's evidence shows the new check failing on the past mistake, or says why no check can catch it",
    "- [ ] Each thread and PR above is read as evidence",
    ...(singles.length === 0
      ? []
      : [
          "",
          `**Other ${repeat.kind} friction, seen once:** fix any that share this cause in the same PR.`,
          "",
          ...singles.map((r) => `- \`${r.target}\`: ${r.sightings[0].detail}`),
        ]),
    "",
    "**Out of scope:**",
    "- Friction of other kinds",
  ].join("\n");

// ---- Effects. Everything that touches the outside world runs inside a step or an agent.

const gh = (args, cwd) =>
  Effect.tryPromise({
    try: () =>
      new Promise((resolve, reject) =>
        execFile("gh", args, { cwd, windowsHide: true, maxBuffer: 16 * 1024 * 1024 }, (error, stdout, stderr) =>
          error ? reject(new Error(`gh ${args.join(" ")}: ${String(stderr || error.message).trim()}`)) : resolve(String(stdout)),
        ),
      ),
    catch: (error) => (error instanceof Error ? error : new Error(String(error))),
  });

/** Each item of a paged GitHub list, with the fields `feedbackOf` reads. */
const ghItems = (path, cwd) =>
  gh(["api", "--paginate", path, "--jq", ".[] | {id, state, body, author_association, html_url, login: .user.login}"], cwd).pipe(
    Effect.map((out) => out.split(/\r?\n/).filter(Boolean).map((line) => JSON.parse(line))),
  );

/** How many of an issue's blockers are open: GitHub's native dependencies, then a `Blocked by` line. */
const openBlockers = (config, number) =>
  Effect.gen(function* () {
    const issue = JSON.parse(yield* gh(["api", `repos/${config.repository}/issues/${number}`], config.project));
    const native = Number(issue.issue_dependencies_summary?.blocked_by ?? 0);
    if (native > 0) return native;
    let open = 0;
    for (const blocker of blockersInBody(issue.body)) {
      const state = (yield* gh(["api", `repos/${config.repository}/issues/${blocker}`, "--jq", ".state"], config.project)).trim();
      if (state === "open") open++;
    }
    return open;
  });


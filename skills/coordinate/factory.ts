// The skills factory: a T3 Code workflow that runs the coordinator's loop for issues labelled
// ready-for-agent, with no coordinator agent and no person to start it.
//
// Install by copying this file to the `workflows` folder of T3 home as `skills-factory.ts`, and
// register each repo under `skills-factory/projects/<owner>/<repo>` in the workflow store.
// factory.md, beside this file, says how. Workflow files import nothing from T3 or Effect: the
// server hands them `T3`, `Effect`, `Schema`, `Option`, `Duration` and `Schedule` as globals.
import { execFile } from "node:child_process";

const { workflow, step, agent, ask, stop, skip, title, every, start, runs, store, issues, pullRequests, Tick } = T3;

const PREFIX = "skills-factory";
const AI_MARKER = "> *This was generated by AI during a build.*";
// Run states that hold a worker slot. A run that waits on a person's answer holds one too.
const ACTIVE = ["running", "waiting", "paused"];
// How many times a run goes round checks, fixes and review before it hands the PR to a person.
const MAX_ROUNDS = 8;

const described = (schema, description) => schema.annotate({ description });

const ModelChoice = Schema.Struct({
  instanceId: Schema.String,
  model: Schema.String,
  options: Schema.optional(
    Schema.Array(Schema.Struct({ id: Schema.String, value: Schema.Union([Schema.String, Schema.Boolean]) })),
  ),
});
const RolePair = Schema.Struct({ default: ModelChoice, backup: Schema.optional(ModelChoice) });

/** One repo's settings, as `setup-skills` writes them to the store. */
const Config = Schema.Struct({
  project: Schema.String,
  repository: Schema.String,
  skillsFolder: Schema.String,
  defaultBranch: Schema.String,
  readyLabel: Schema.String,
  needsTriageLabel: Schema.String,
  verifySkill: Schema.NullOr(Schema.String),
  maxActive: Schema.Number,
  mergeMethod: Schema.Literals(["merge", "squash", "rebase"]),
  enabled: Schema.Boolean,
  worker: Schema.optional(RolePair),
  reviewer: Schema.optional(RolePair),
});

const IssueRef = Schema.Struct({
  number: Schema.String,
  displayKey: Schema.String,
  title: Schema.String,
  url: Schema.String,
});

const ShipInput = Schema.Struct({ config: Config, issue: IssueRef });

const Lines = (description) => described(Schema.Array(Schema.String), description);
const FOLLOW_UPS = "Follow-ups: work worth doing outside your task, one line each. Empty when none.";
const FRICTION = "Friction: what cost you time, one line each, naming the file or command. Empty when none.";

const WorkerResult = Schema.Struct({
  status: described(
    Schema.Literals(["DONE", "BLOCKED", "FAILED"]),
    "DONE when your path finished. BLOCKED when you need something before you can go on. FAILED when something stopped you.",
  ),
  path: described(Schema.Literals(["answer", "talk", "build", "split"]), "The path you took, as worker.md names them."),
  summary: described(
    Schema.String,
    "Your result: the answer, what you settled, or what you built, with your evidence, what you skipped, and what stays unproven. For BLOCKED or FAILED, what you need or what stopped you.",
  ),
  pr: described(Schema.NullOr(Schema.String), "The full URL of the PR you opened or continued. Null when there is none."),
  headSha: described(Schema.NullOr(Schema.String), "The PR's head SHA after your last push. Null when there is no PR."),
  followUps: Lines(FOLLOW_UPS),
  friction: Lines(FRICTION),
});

const Verdict = Schema.Struct({
  status: described(
    Schema.Literals(["PASS", "NO AGREEMENT", "FAILED"]),
    "Your verdict, or FAILED when you could not reach one.",
  ),
  headSha: described(Schema.NullOr(Schema.String), "The head SHA your verdict covers. Null for FAILED."),
  comment: described(Schema.NullOr(Schema.String), "The URL of your verdict comment. Null when you posted none."),
  summary: described(Schema.String, "What you proved, and for FAILED, what stopped you."),
  open: described(
    Schema.Array(Schema.Struct({ finding: Schema.String, reviewer: Schema.String, worker: Schema.String })),
    "Each finding still open, with your position and the worker's. Empty for PASS.",
  ),
  followUps: Lines(FOLLOW_UPS),
  friction: Lines(FRICTION),
});

// ---- Helpers. Everything that touches the outside world runs inside a step or an agent.

const gh = (args, cwd) =>
  Effect.tryPromise({
    try: () =>
      new Promise((resolve, reject) =>
        execFile("gh", args, { cwd, windowsHide: true, maxBuffer: 16 * 1024 * 1024 }, (error, stdout, stderr) =>
          error ? reject(new Error(`gh ${args.join(" ")}: ${String(stderr || error.message).trim()}`)) : resolve(String(stdout)),
        ),
      ),
    catch: (error) => (error instanceof Error ? error : new Error(String(error))),
  });

const issueNumber = (issue) => String(issue.displayKey).replace(/^#/, "");

/** Issue numbers named in a `Blocked by` line or section of an issue body. */
const blockersInBody = (body) => {
  const found = new Set();
  const lines = String(body ?? "").split(/\r?\n/);
  for (let i = 0; i < lines.length; i++) {
    const inline = /^\s*\**blocked by\**:?\s*(.*)$/i.exec(lines[i]);
    const heading = /^#{1,6}\s*blocked by\s*$/i.test(lines[i]);
    if (!inline && !heading) continue;
    let text = inline ? inline[1] : "";
    // A section runs until the next heading.
    for (let j = i + 1; heading && j < lines.length && !/^#{1,6}\s/.test(lines[j]); j++) text += ` ${lines[j]}`;
    for (const match of text.matchAll(/#(\d+)/g)) found.add(match[1]);
  }
  return [...found];
};

/** How many of an issue's blockers are open: GitHub's native dependencies, then a `Blocked by` line. */
const openBlockers = (config, number) =>
  Effect.gen(function* () {
    const issue = JSON.parse(yield* gh(["api", `repos/${config.repository}/issues/${number}`], config.project));
    const native = Number(issue.issue_dependencies_summary?.blocked_by ?? 0);
    if (native > 0) return native;
    let open = 0;
    for (const blocker of blockersInBody(issue.body)) {
      const state = (yield* gh(["api", `repos/${config.repository}/issues/${blocker}`, "--jq", ".state"], config.project)).trim();
      if (state === "open") open++;
    }
    return open;
  });

const issueAddress = (input) => ({ project: input.config.project, url: input.issue.url });

const workerBrief = (input) => {
  const { config, issue } = input;
  return [
    `Read ${config.skillsFolder}/coordinate/rules.md, then ${config.skillsFolder}/coordinate/worker.md, before anything else.`,
    "",
    `Task: ${issue.url} (${issue.displayKey} ${issue.title})`,
    `Skills folder: ${config.skillsFolder}`,
    `Default branch: ${config.defaultBranch}`,
    `Verify skill: ${config.verifySkill ?? "none"}`,
    "Coordinator: a T3 workflow. Follow \"In a T3 workflow\" in rules.md.",
    "",
    "You may start the subagents your skills call for.",
  ].join("\n");
};

const reviewerBrief = (input, pr, workerThread, earlier, rulings) => {
  const { config, issue } = input;
  return [
    `Read ${config.skillsFolder}/coordinate/rules.md, then ${config.skillsFolder}/coordinate/reviewer.md, before anything else.`,
    "",
    `Review PR ${pr}. You did not write it.`,
    `Task: ${issue.url} (${issue.displayKey} ${issue.title})`,
    `Worker thread: ${workerThread}`,
    `Earlier verdict: ${earlier}`,
    `Rulings: ${rulings}`,
    `Skills folder: ${config.skillsFolder}`,
    `Default branch: ${config.defaultBranch}`,
    `Verify skill: ${config.verifySkill ?? "none"}`,
    "Coordinator: a T3 workflow. Follow \"In a T3 workflow\" in rules.md.",
    "",
    "You may start the subagents your skills call for.",
  ].join("\n");
};

const wokeBrief = (what) =>
  `The T3 workflow that runs your task woke you: ${what} Settle it as worker.md says, push, and return your result as data with the new head SHA.`;

const worktreeOf = (config) => ({
  type: "worktree",
  baseRef: `origin/${config.defaultBranch}`,
  startFromOrigin: true,
});

/** An agent on the role's default model, then once more on its backup when the first attempt fails. */
const hire = Effect.fn(function* (name, options, pair) {
  const first = yield* agent.try(name, pair ? { ...options, model: pair.default } : options);
  if (first.outcome === "done") return first;
  const earlier = first.thread ? ` Its thread is ${first.thread.threadId}. Continue its branch and PR if it left any.` : "";
  const fallback = pair ? { model: pair.backup ?? pair.default } : {};
  return yield* agent.try(`${name}-again`, {
    ...options,
    ...fallback,
    brief: `${options.brief}\n\nAn earlier attempt at this failed: ${first.reason}.${earlier}`,
  });
});

const ship = workflow(
  "skills-factory-ship",
  {
    version: 1,
    payload: ShipInput,
    // Whatever way the run ends, the issue leaves the queue. A person adds the label back to retry.
    onEnd: (input) =>
      gh(
        ["issue", "edit", input.issue.number, "--repo", input.config.repository, "--remove-label", input.config.readyLabel],
        input.config.project,
      ),
  },
  Effect.fn(function* (input, run) {
    const { config, issue } = input;
    yield* title(`${issue.displayKey} ${issue.title}`);

    const followUps = [];
    const friction = [];
    const keep = (result) => {
      followUps.push(...result.followUps);
      friction.push(...result.friction);
    };

    /** File the follow-ups, keep the friction, and leave a note on the issue when there is one. */
    const wrapUp = Effect.fn(function* (note) {
      for (const [i, line] of followUps.entries()) {
        yield* step(
          `follow-up-${i + 1}`,
          { returns: Schema.Void },
          issues
            .create({
              project: config.project,
              title: line.length > 80 ? `${line.slice(0, 77)}...` : line,
              body: `${AI_MARKER}\n\n${line}\n\nCame up while the skills factory worked on ${issue.url}.`,
              labels: [config.needsTriageLabel],
            })
            .pipe(Effect.asVoid),
        );
      }
      if (friction.length > 0) {
        yield* step(
          "friction",
          { returns: Schema.Void },
          store.entry(`${PREFIX}/friction/${config.repository}/${run.id}`, Schema.Array(Schema.String)).set(friction),
        );
      }
      if (note) {
        yield* step("note", { returns: Schema.Void }, issues.comment(issueAddress(input), `${AI_MARKER}\n\n${note}`));
      }
    });

    /** End the run as stopped, and tell the issue why and how to try again. */
    const halt = Effect.fn(function* (reason) {
      yield* wrapUp(
        `The skills factory stopped on this issue: ${reason}\n\nIt removed \`${config.readyLabel}\`. Add the label back to try again. Run \`${run.id}\` in T3 Code holds the details.`,
      );
      return yield* stop(reason);
    });

    // ---- The worker sizes the task and takes its path.
    const worker = yield* hire(
      "worker",
      {
        project: config.project,
        issue: issueAddress(input),
        workspace: worktreeOf(config),
        title: `Worker: ${issue.displayKey} ${issue.title}`,
        brief: workerBrief(input),
        returns: WorkerResult,
        quiet: "2 hours",
        timeout: "24 hours",
      },
      config.worker,
    );
    if (worker.outcome === "failed") return yield* halt(`the worker failed twice: ${worker.reason}`);
    const workerThread = worker.thread;
    let result = worker.value;
    keep(result);
    if (result.status !== "DONE") return yield* halt(`the worker returned ${result.status}: ${result.summary}`);
    if (result.path !== "build" || result.pr === null) {
      yield* wrapUp(`The skills factory finished this issue on the ${result.path} path.\n\n${result.summary}`);
      return { path: result.path, summary: result.summary };
    }

    // ---- The PR's path: green checks, a review of the current head, then a person's go to merge.
    const pr = { project: config.project, url: result.pr };
    let verdict = null; // { headSha, comment, approved }
    let rulings = "none";

    /** Wake the worker on its own thread, and take what it returns. */
    const wake = Effect.fn(function* (name, what) {
      const woken = yield* agent.try(name, { thread: workerThread, brief: wokeBrief(what), returns: WorkerResult, quiet: "2 hours", timeout: "12 hours" });
      if (woken.outcome === "failed") return yield* halt(`the worker failed after it was woken: ${woken.reason}`);
      keep(woken.value);
      if (woken.value.status !== "DONE") return yield* halt(`the worker returned ${woken.value.status}: ${woken.value.summary}`);
      return woken.value;
    });

    for (let round = 1; round <= MAX_ROUNDS; round++) {
      const at = yield* pullRequests.wait(`checks-${round}`, pr, { until: "checks", timeout: "3 hours" });
      if (Option.isNone(at)) return yield* halt(`the checks on ${pr.url} were still running after 3 hours.`);
      const standing = at.value;
      if (standing.state === "merged") {
        yield* wrapUp(null);
        return { path: "build", pr: pr.url, merged: "outside the factory" };
      }
      if (standing.state === "closed") return yield* halt(`${pr.url} was closed outside the factory.`);
      if (standing.checks === "failing" || standing.mergeability === "conflicting") {
        const what = standing.checks === "failing" ? "a check fails on your PR." : "your PR conflicts with main.";
        result = yield* wake(`fix-${round}`, `${what} PR: ${pr.url}.`);
        continue;
      }

      const head = yield* step(
        `head-${round}`,
        { returns: Schema.String },
        pullRequests.read(pr).pipe(Effect.map((detail) => detail.headSha ?? "")),
      );

      if (verdict === null || verdict.headSha !== head) {
        const review = yield* hire(
          `review-${round}`,
          {
            project: config.project,
            workspace: worktreeOf(config),
            title: `Reviewer: ${issue.displayKey} ${issue.title}`,
            brief: reviewerBrief(input, pr.url, workerThread.threadId, verdict?.comment ?? "none", rulings),
            returns: Verdict,
            timeout: "8 hours",
          },
          config.reviewer,
        );
        if (review.outcome === "failed") return yield* halt(`the reviewer failed twice: ${review.reason}`);
        keep(review.value);
        const v = review.value;
        if (v.status === "FAILED" || v.headSha === null) return yield* halt(`the reviewer could not reach a verdict: ${v.summary}`);
        if (v.status === "PASS") {
          verdict = { headSha: v.headSha, comment: v.comment, approved: false };
          continue; // Back to the checks, now at the head the verdict names.
        }
        const ruling = yield* ask(`ruling-${round}`, {
          title: `${issue.displayKey}: the reviewer and the worker disagree on ${pr.url}`,
          choices: ["land it as it is", "send my rulings to the worker", "stop"],
          data: { pr: pr.url, head: v.headSha, verdict: v.comment, open: v.open },
          timeout: "7 days",
        });
        if (Option.isNone(ruling)) return yield* halt("nobody ruled on the open findings within 7 days.");
        if (ruling.value.choice === "stop") return yield* halt("the user stopped it at the ruling.");
        if (ruling.value.choice === "land it as it is") {
          verdict = { headSha: v.headSha, comment: v.comment, approved: true };
          continue;
        }
        rulings = ruling.value.reason?.trim() || "The user sided with the reviewer on every open finding.";
        verdict = { headSha: v.headSha, comment: v.comment, approved: false };
        result = yield* wake(`rulings-${round}`, `the user ruled on the reviewer's open findings on ${pr.url}: ${rulings}`);
        continue;
      }

      // Checks are green at the head the verdict covers.
      let go = verdict.approved;
      if (!go) {
        const answer = yield* ask(`merge-${round}`, {
          title: `${issue.displayKey}: merge ${pr.url}?`,
          choices: ["merge", "I will merge it", "stop"],
          data: { pr: pr.url, head, verdict: verdict.comment, summary: result.summary },
          timeout: "7 days",
        });
        if (Option.isNone(answer)) return yield* halt("nobody answered the merge question within 7 days.");
        if (answer.value.choice === "stop") return yield* halt("the user stopped it before the merge.");
        if (answer.value.choice === "I will merge it") {
          const merged = yield* pullRequests.wait(`merged-${round}`, pr, { until: "merged", timeout: "14 days" });
          if (Option.isNone(merged) || merged.value.state !== "merged") {
            return yield* halt(`${pr.url} was not merged within 14 days, or was closed.`);
          }
          yield* wrapUp(null);
          return { path: "build", pr: pr.url, merged: "by the user" };
        }
        go = true;
      }

      // `--match-head-commit` makes GitHub refuse the merge if the head moved since the review.
      const merge = yield* step.try(
        `merge-${round}`,
        { returns: Schema.Void },
        gh(["pr", "merge", pr.url, `--${config.mergeMethod}`, "--match-head-commit", head], config.project).pipe(Effect.asVoid),
      );
      if (merge.outcome === "failed") {
        const now = yield* step(
          `head-after-merge-${round}`,
          { returns: Schema.String },
          pullRequests.read(pr).pipe(Effect.map((detail) => detail.headSha ?? "")),
        );
        if (now !== head) continue; // The head moved, so it goes back through checks and review.
        return yield* halt(`the merge of ${pr.url} failed: ${merge.reason}`);
      }
      yield* step.try(`delete-branch-${round}`, { returns: Schema.Void }, pullRequests.act(pr, "delete-branch"));
      yield* wrapUp(null);
      return { path: "build", pr: pr.url, merged: head };
    }
    return yield* halt(`${pr.url} went round checks and review ${MAX_ROUNDS} times without landing.`);
  }),
);

workflow(
  "skills-factory-dispatch",
  { version: 1, payload: Tick, triggers: [every("10 minutes")] },
  Effect.fn(function* () {
    const started = yield* step(
      "dispatch",
      { returns: Schema.Array(Schema.String) },
      Effect.gen(function* () {
        const projects = yield* store.entries(`${PREFIX}/projects/`, Config);
        const earlier = yield* runs({ workflow: ship });
        const keys = [];
        for (const { value: config } of projects) {
          if (!config.enabled) continue;
          const own = `ship/${config.repository}/`;
          let room = config.maxActive - earlier.filter((r) => r.key?.startsWith(own) && ACTIVE.includes(r.status)).length;
          if (room <= 0) continue;
          const ready = yield* issues.list({ project: config.project, labels: [config.readyLabel], limit: 100 });
          // Oldest first, so nothing waits behind newer work for long.
          const queue = [...ready].sort((a, b) => String(a.createdAt).localeCompare(String(b.createdAt)));
          for (const issue of queue) {
            if (room <= 0) break;
            const number = issueNumber(issue);
            const prefix = `${own}${number}/`;
            const tries = earlier.filter((r) => r.key?.startsWith(prefix));
            if (tries.some((r) => ACTIVE.includes(r.status))) continue;
            if ((yield* openBlockers(config, number)) > 0) continue;
            // A new key per try: a key already used gives back the run that has it.
            const key = `${prefix}${tries.length + 1}`;
            yield* start(ship, { config, issue: { number, displayKey: issue.displayKey, title: issue.title, url: issue.url } }, { key });
            keys.push(key);
            room--;
          }
        }
        return keys;
      }),
    );
    if (started.length === 0) return yield* skip("no issue to start");
    return started;
  }),
);

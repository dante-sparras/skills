const feedbackOf = ({ reviews, comments, lineComments, handled, self = null }) => {
  const collaborator = (item) => COLLABORATORS.includes(item.author_association) && !isBot(item);
  const byCollaborator = (item) => collaborator(item) && !isAgentPost(item, self);
  const byOutsider = (item) =>
    !COLLABORATORS.includes(item.author_association) && !isAgentPost(item, self) && !isBot(item) && String(item.body ?? "").trim() !== "";
  const latest = new Map();
  for (const review of reviews.filter(collaborator)) {
    if (["APPROVED", "CHANGES_REQUESTED", "DISMISSED"].includes(review.state)) latest.set(review.login, review.state);
  }
  const said = [
    ...reviews
      .filter((review) => (review.state === "CHANGES_REQUESTED" ? collaborator(review) : byCollaborator(review)))
      .filter((review) => review.state === "CHANGES_REQUESTED" || (review.state !== "APPROVED" && String(review.body ?? "").trim() !== ""))
      .map((review) => ({ id: `review-${review.id}`, author: review.login, url: review.html_url, text: `${review.state}: ${review.body ?? ""}` })),
    ...comments.filter(byCollaborator).map((c) => ({ id: `comment-${c.id}`, author: c.login, url: c.html_url, text: c.body ?? "" })),
    ...lineComments.filter(byCollaborator).map((c) => ({ id: `line-${c.id}`, author: c.login, url: c.html_url, text: c.body ?? "" })),
  ];
  const outside = [
    ...reviews.filter(byOutsider).map((review) => ({ id: `review-${review.id}`, author: review.login, url: review.html_url, text: review.body })),
    ...comments.filter(byOutsider).map((c) => ({ id: `comment-${c.id}`, author: c.login, url: c.html_url, text: c.body })),
    ...lineComments.filter(byOutsider).map((c) => ({ id: `line-${c.id}`, author: c.login, url: c.html_url, text: c.body })),
  ];
  const unhandled = (items) =>
    items.filter((item) => !handled.includes(item.id)).map((item) => ({ ...item, text: cut(item.text.trim(), 600) }));
  return {
    held: [...latest].filter(([, state]) => state === "CHANGES_REQUESTED").map(([login]) => login),
    fresh: unhandled(said),
    outside: unhandled(outside),
  };
};


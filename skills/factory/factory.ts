const approvalEvents = (events) => (events ?? []).filter((event) => event.label === LABELS.approved && ["labeled", "unlabeled"].includes(event.event));

const newestLabelEvent = (events) => approvalEvents(events).reduce((newest, event) => Math.max(newest, Number(event.id) || 0), 0);

const lastApproval = (events, approver = null) => {
  const newest = approvalEvents(events).reduce((best, event) => (best === null || Number(event.id) > Number(best.id) ? event : best), null);
  if (newest === null || newest.event !== "labeled") return 0;
  if (approver && newest.actor !== approver) return 0;
  return Number(newest.id) || 0;
};

const approvalOf = (pr, head, events, after, approver = null) => {
  const labelled = (pr.labels ?? []).some((label) => label.name === LABELS.approved);
  if (labelled && lastApproval(events, approver) > after) return { approved: true, by: "label" };
  const latest = new Map();
  for (const review of pr.reviews ?? []) {
    if (!COLLABORATORS.includes(review.authorAssociation) || !["APPROVED", "CHANGES_REQUESTED", "DISMISSED"].includes(review.state)) continue;
    latest.set(review.author?.login, review);
  }
  const reviews = [...latest.values()];
  const approving = reviews.some((review) => review.state === "APPROVED" && review.commit?.oid === head && (!approver || review.author?.login === approver));
  const holding = reviews.some((review) => review.state === "CHANGES_REQUESTED");
  return approving && !holding ? { approved: true, by: "review" } : { approved: false, by: null };
};


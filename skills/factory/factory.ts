const worktreeOf = (config) => ({
  type: "worktree",
  baseRef: `origin/${config.defaultBranch}`,
  startFromOrigin: true,
});

/** An agent on the role's default model, then once more on its backup when the first attempt fails. */
const hire = Effect.fn(function* (name, options, pair) {
  const first = yield* agent.try(name, pair ? { ...options, model: pair.default } : options);
  if (first.outcome === "done") return first;
  const earlier = first.thread ? ` Its thread is ${first.thread.threadId}. Continue its branch and PR if it left any.` : "";
  const fallback = pair ? { model: pair.backup ?? pair.default } : {};
  return yield* agent.try(`${name}-again`, {
    ...options,
    ...fallback,
    brief: `${options.brief}\n\nAn earlier attempt at this failed: ${first.reason}.${earlier}`,
  });
});

/**
 * Count one friction against every earlier run. When it reaches its count, file a guardrail
 * issue in ready-for-agent, so the factory builds the fix. A friction already filed adds a comment.
 */
const countRepeat = Effect.fn(function* (config, name, seen) {
  const key = repeatKey(config.repository, seen.kind, seen.target);
  const entry = store.entry(key, Repeat);
  const sighting = { run: seen.run, task: seen.task, thread: seen.thread, pr: seen.pr, detail: seen.detail };
  const needed = seen.kind === "broken" ? 1 : REPEAT_AFTER;
  // Count the sighting, and in the same write claim the issue when this is the sighting that
  // makes a repeat. Two runs that end together cannot both claim it. A claim names its time, so
  // one that its run never finished goes stale, and a later sighting takes it over.
  const counted = yield* step.try(
    name,
    { returns: Repeat },
    Effect.gen(function* () {
      const now = new Date().toISOString();
      const claim = `claimed ${now} by ${seen.run}`;
      let filed = null;
      const before = yield* entry.get;
      // An issue that was closed did not stop the friction, so the count starts over from here.
      const reopened = Option.isSome(before) && String(before.value.filed ?? "").startsWith("http") && (yield* issueState(config, before.value.filed)) !== "OPEN";
      const next = yield* entry.update((found) => {
        const earlier = Option.isSome(found) ? found.value : { kind: seen.kind, target: seen.target, sightings: [], filed: null };
        const restart = reopened && earlier.filed === before.value.filed;
        const sightings = restart ? [sighting] : [...earlier.sightings, sighting];
        const free = restart || earlier.filed === null || claimIsStale(earlier.filed, now);
        filed = free && runsThatSaw(sightings) >= needed ? claim : restart ? null : earlier.filed;
        return { ...earlier, sightings, filed };
      });
      return { ...Option.getOrThrow(next), filed: filed === claim ? "mine" : Option.getOrThrow(next).filed };
    }),
  );
  if (counted.outcome === "failed" || counted.value.filed === null) return;
  const repeat = counted.value;
  if (repeat.filed !== "mine") {
    // Another run filed the issue, or is filing it now. A filed issue hears of this sighting.
    if (!repeat.filed.startsWith("http")) return;
    yield* step.try(
      `${name}-seen-again`,
      { returns: Schema.Void },
      issues.comment(issueAddress(config, repeat.filed), `${AI_MARKER}\n\nSeen again:\n\n${sightingLine(sighting)}`),
    );
    return;
  }
  const singles = yield* step.try(
    `${name}-singles`,
    { returns: Schema.Array(Repeat) },
    store
      .entries(`${PREFIX}/repeats/${config.repository}/${seen.kind}/`, Repeat)
      .pipe(Effect.map((rows) => rows.filter((row) => row.key !== key && row.value.filed === null && row.value.sightings.length === 1).map((row) => row.value))),
  );
  const labels = LABELS;
  const url = yield* step.try(
    `${name}-file`,
    { returns: Schema.String },
    createIssue(config, `Guardrail: ${seen.kind} at ${repeat.target}`, guardrailBrief(repeat, singles.outcome === "failed" ? [] : singles.value), [labels.ready, labels.enhancement]),
  );
  // The issue's link takes the claim's place. With no issue, the claim is given up, so the next sighting files it.
  yield* step.try(
    `${name}-filed`,
    { returns: Schema.Void },
    entry.update((found) => (Option.isSome(found) ? { ...found.value, filed: url.outcome === "failed" ? null : url.value } : undefined)).pipe(Effect.asVoid),
  );
});

/** What a run collects from its agents, and how it files that when the run ends. */
const ledgerOf = (config, run, task) => {
  const followUps = [];
  const sightings = [];
  // A worker that is woken may return its whole list again, so each follow-up and each
  // friction is kept once per run.
  const keep = (result, where) => {
    for (const line of result.followUps) {
      if (!followUps.some((kept) => titleKey(cut(kept, 80)) === titleKey(cut(line, 80)))) followUps.push(line);
    }
    for (const item of [...result.friction, ...(result.checkable ?? [])]) {
      const key = repeatKey(config.repository, item.kind, item.target);
      if (sightings.some((seen) => repeatKey(config.repository, seen.kind, seen.target) === key)) continue;
      sightings.push({ ...item, run: run.id, task, thread: where.thread ?? null, pr: where.pr ?? null });
    }
  };
  /**
   * File the follow-ups, count the friction, and leave a note on the task when there is one. A
   * follow-up that matches an open issue's title adds a comment there in place of a new issue.
   */
  const wrapUp = Effect.fn(function* (note) {
    for (const [i, line] of followUps.entries()) {
      yield* step.try(
        `follow-up-${i + 1}`,
        { returns: Schema.Void },
        Effect.gen(function* () {
          const title = cut(line, 80);
          const open = yield* findOpenIssue(config, title);
          if (open !== null) {
            yield* issues.comment(issueAddress(config, open), `${AI_MARKER}\n\nThis came up again while the skills factory worked on ${task}:\n\n${line}`);
            return;
          }
          yield* issues.create({
            project: config.project,
            title,
            body: `${AI_MARKER}\n\n${line}\n\nCame up while the skills factory worked on ${task}.`,
            labels: [LABELS.triage],
          });
        }),
      );
    }
    for (const [i, seen] of sightings.entries()) yield* countRepeat(config, `friction-${i + 1}`, seen);
    if (note) yield* step.try("note", { returns: Schema.Void }, issues.comment(issueAddress(config, task), `${AI_MARKER}\n\n${note}`));
  });
  return { keep, wrapUp };
};

/** The runs of `workflow` for one issue, whose keys are `<own><number>/<try>`. */
const triesOf = (all, own, number) => all.filter((r) => r.key?.startsWith(`${own}${number}/`));
const specOwn = (config) => `spec/${config.repository}/`;
const shipOwn = (config) => `ship/${config.repository}/`;

/**
 * After a ticket's PR merged: close the ticket if the merge did not, and when it was its spec's
 * last open ticket, put the spec in ready-for-agent, where the dispatcher starts its check. A spec
 * gets one check that finishes: once the gaps it filed have landed too, the spec closes.
 */
const afterMerge = (config, issue, closing) =>
  Effect.gen(function* () {
    const repo = config.repository;
    const cwd = config.project;
    const ticket = yield* readIssue(config, issue.number);
    if (ticket.state === "open") yield* gh(["issue", "close", issue.number, "--repo", repo, "--comment", `${AI_MARKER}\n\n${closing}`], cwd);
    const native = yield* gh(["api", `repos/${repo}/issues/${issue.number}/parent`, "--jq", ".number"], cwd).pipe(
      Effect.map((out) => out.trim()),
      Effect.orElseSucceed(() => ""),
    );
    const parent = native || parentInBody(ticket.body);
    if (!parent) return "no spec";
    // A spec's tickets are counted as its sub-issues. A ticket that names its spec only in its
    // body is linked now, so the count below holds it.
    if (!native) yield* gh(["issue", "edit", parent, "--repo", repo, "--add-sub-issue", issue.number], cwd).pipe(Effect.orElseSucceed(() => ""));
    const spec = yield* readIssue(config, parent);
    if (spec.state !== "open" || !spec.labels.some((label) => label.name === LABELS.spec)) return `#${parent} is not an open spec`;
    if (!(yield* allTicketsClosed(config, parent))) return `spec #${parent} has open tickets`;
    // The trailing slash keeps spec 123's runs out of spec 12's.
    const earlier = triesOf(yield* runs({ workflow: specCheck, keyPrefix: `${specOwn(config)}${parent}/` }), specOwn(config), parent);
    if (earlier.some((r) => ACTIVE.includes(r.status))) return `the check of spec #${parent} is still running`;
    if (earlier.some((r) => r.status === "completed")) {
      yield* gh(
        ["issue", "close", parent, "--repo", repo, "--comment", `${AI_MARKER}\n\nEvery ticket of this spec has landed, and so has each gap its spec check found.`],
        cwd,
      );
      return `closed spec #${parent}`;
    }
    yield* gh(["issue", "edit", parent, "--repo", repo, "--add-label", LABELS.ready], cwd);
    return `put spec #${parent} in ${LABELS.ready} for its check`;
  });

const ship = workflow(
  "skills-factory-ship",
  {
    version: 14,
    payload: ShipInput,
    // The issue leaves the queue however the run ends, unless the run parked it to wait on
    // another issue. A run that did not finish moves it to needs-triage, so a person sees it the
    // next time they triage. Adding ready-for-agent back in its place retries it.
    onEnd: (input, end) =>
      Effect.gen(function* () {
        const { config, issue } = input;
        const parked = yield* store.entry(resumeKey(config, issue), Resume).get;
        if (end.outcome === "stopped" && Option.isSome(parked)) return;
        const triage = end.outcome === "completed" ? [] : ["--add-label", LABELS.triage];
        yield* gh(["issue", "edit", issue.number, "--repo", config.repository, "--remove-label", LABELS.ready, ...triage], config.project);
      }),
  },
  Effect.fn(function* (input, run) {
    const { config, issue } = input;
    yield* title(`${issue.displayKey} ${issue.title}`);
    const ledger = ledgerOf(config, run, issue.url);

    /** End the run as stopped, and tell the issue why and how to try again. */
    const halt = Effect.fn(function* (reason) {
      yield* ledger.wrapUp(
        `The skills factory stopped on this issue: ${reason}\n\nIt moved the issue from \`${LABELS.ready}\` to \`${LABELS.triage}\`. Put \`${LABELS.ready}\` back in its place to try again. Run \`${run.id}\` in T3 Code holds the details.`,
      );
      return yield* stop(reason);
    });

    const resumed = yield* step(
      "resume",
      { returns: Schema.NullOr(Resume) },
      Effect.gen(function* () {
        const entry = store.entry(resumeKey(config, issue), Resume);
        const found = yield* entry.get;
        if (Option.isNone(found)) return null;
        yield* entry.delete;
        return found.value;
      }),
    );
    const verifySkill = yield* step("verify-skill", { returns: Schema.NullOr(Schema.String) }, findVerifySkill(config));
    const roles = yield* step("roles", { returns: Roles }, rolesOf(config));
    // A retried issue may have an open PR already. Without this the new worker opens a second one.
    const left = yield* step.try("open-prs", { returns: Schema.Array(Schema.String) }, openPrsFor(config, issue.number));
    const openPrs = left.outcome === "failed" ? [] : left.value;

    // Whatever waited for the user's review is this run's to carry on now. Left in the store, it
    // would have the pass start this work again after the run.
    yield* step.try("carry-on", { returns: Schema.Void }, readyEntry(config, issue.number).delete);

    // ---- The worker builds the issue. A run that picks up a PR that waited for review has no
    // worker to hire: it goes on in the thread of the worker that opened the PR.
    let workerThread;
    let first;
    if (input.again) {
      workerThread = { threadId: input.again.thread };
      first = { status: "DONE", question: null, blockedOn: null, summary: `Picked up again: ${input.again.why}.`, pr: input.again.pr, headSha: null, followUps: [], friction: [] };
    } else {
      const worker = yield* hire(
        "worker",
        {
          project: config.project,
          issue: issueAddress(config, issue.url),
          workspace: worktreeOf(config),
          title: `Worker: ${issue.displayKey} ${issue.title}`,
          brief: workerBrief(input, verifySkill, resumed, openPrs),
          returns: WorkerResult,
          quiet: "2 hours",
          timeout: "24 hours",
        },
        roles.worker,
      );
      if (worker.outcome === "failed") return yield* halt(`the worker failed twice: ${worker.reason}`);
      workerThread = worker.thread;
      ledger.keep(worker.value, { thread: workerThread.threadId, pr: worker.value.pr });
      first = worker.value;
    }

    /**
     * Bring each question the worker returns to the user, where every other question of the run
     * waits, and wake the worker on its own thread with the answer. Gives the first other result.
     */
    let asked = 0;
    /**
     * Ask the user in the worker's thread, with its question tool, so T3 shows that thread as
     * waiting on them. A thread that cannot ask leaves the question to the Workflows page.
     */
    const askUser = Effect.fn(function* (name, question) {
      const asked = yield* agent.try(`${name}-thread`, { thread: workerThread, brief: askBrief(question), returns: Answer, timeout: question.timeout });
      const came = answerOf(asked, question.choices);
      if (came.answered) return Option.some(came.answered);
      if (came.timedOut) return Option.none();
      return yield* ask(name, question);
    });

    const answered = Effect.fn(function* (value) {
      let current = value;
      while (current.status === "QUESTION") {
        asked++;
        if (asked > MAX_QUESTIONS) return yield* halt(`the worker asked more than ${MAX_QUESTIONS} questions.`);
        const text = current.question?.text ?? current.summary;
        const offered = [...new Set(current.question?.choices ?? [])].slice(0, 4);
        const answer = yield* askUser(`question-${asked}`, {
          title: `${issue.displayKey}: ${cut(text, 200)}`,
          choices: offered.length > 0 ? offered : ["answered in my note"],
          data: { issue: issue.url, question: text, thread: workerThread.threadId },
          timeout: "7 days",
        });
        if (Option.isNone(answer)) return yield* halt(`nobody answered the worker's question within 7 days: ${cut(text, 200)}`);
        const note = answer.value.reason?.trim();
        const woken = yield* agent.try(`answer-${asked}`, {
          thread: workerThread,
          brief: `The user answered your question: ${answer.value.choice}${note ? `. Their note: ${note}` : ""}. Go on with your task, and return your result as data. Settle your thread with \`t3_thread_organize\` before you return.`,
          returns: WorkerResult,
          quiet: "2 hours",
          timeout: "24 hours",
        });
        if (woken.outcome === "failed") return yield* halt(`the worker failed after the user answered it: ${woken.reason}`);
        ledger.keep(woken.value, { thread: workerThread.threadId, pr: woken.value.pr });
        current = woken.value;
      }
      return current;
    });
    let result = yield* answered(first);

    // ---- A missing verify skill parks the issue behind a new issue that creates it.
    if (result.status === "BLOCKED" && result.blockedOn === "verify-skill") {
      const labels = LABELS;
      // One issue per repo: the run that claims the key files it, and the rest wait on it. The
      // claim is the store's atomic update, so two runs that park at once file one issue.
      const claims = store.entry(`${PREFIX}/verify-skill-issue/${config.repository}`, VerifyClaim);
      let verifyIssue = null;
      for (let attempt = 1; attempt <= 6 && verifyIssue === null; attempt++) {
        const held = yield* step(
          `verify-skill-claim-${attempt}`,
          { returns: VerifyClaim },
          claims
            .update((found) => {
              if (Option.isNone(found)) return { run: run.id, url: null };
              // A claim that never got its issue in five minutes is taken over.
              if (found.value.url === null && attempt === 6) return { run: run.id, url: null };
              return found.value;
            })
            .pipe(Effect.map((next) => Option.getOrThrow(next))),
        );
        if (held.url !== null) {
          const open = yield* step(`verify-skill-open-${attempt}`, { returns: Schema.String }, issueState(config, held.url));
          if (open === "OPEN") {
            verifyIssue = held.url;
            continue;
          }
          // The last one closed, yet a worker still found no verify skill: claim the key for a new one.
          yield* step(
            `verify-skill-reclaim-${attempt}`,
            { returns: Schema.Void },
            claims
              .update((found) => (Option.isNone(found) ? undefined : found.value.url === held.url ? { run: run.id, url: null } : found.value))
              .pipe(Effect.asVoid),
          );
          continue;
        }
        if (held.run === run.id) {
          const url = yield* step(
            "verify-skill-file",
            { returns: Schema.String },
            createIssue(
              config,
              "Create this repo's verify skill",
              [
                AI_MARKER,
                "",
                "## Agent Brief",
                "",
                "**Category:** enhancement",
                "**Route:** change",
                "**Summary:** Create this repo's verify skill with the `create-verify-skill` skill.",
                "",
                "**Current behavior:**",
                `The repo has no verify skill, so a worker could not prove its change on the running app: ${issue.url}.`,
                "",
                "**Desired behavior:**",
                "A `verify-<app>` skill under `.claude/skills/` that launches the app, drives it, and captures evidence.",
                "",
                "**Acceptance criteria:**",
                "- [ ] A fresh agent ran the skill cold and passed, as `create-verify-skill` says",
              ].join("\n"),
              [labels.ready, labels.enhancement],
            ),
          );
          yield* step("verify-skill-filed", { returns: Schema.Void }, claims.set({ run: run.id, url }));
          verifyIssue = url;
          continue;
        }
        yield* sleep(`verify-skill-wait-${attempt}`, "1 minute");
      }
      if (verifyIssue === null) return yield* halt("it could not claim or find the issue that creates the verify skill.");
      const blocker = verifyIssue.split("/").pop();
      const linked = yield* step.try(
        "wait-on-verify-skill",
        { returns: Schema.Void },
        Effect.gen(function* () {
          const id = (yield* gh(["api", `repos/${config.repository}/issues/${blocker}`, "--jq", ".id"], config.project)).trim();
          yield* gh(["api", "--method", "POST", `repos/${config.repository}/issues/${issue.number}/dependencies/blocked_by`, "-F", `issue_id=${id}`], config.project);
        }),
      );
      if (linked.outcome === "failed") {
        // Without native dependencies, a `Blocked by` line holds it back just the same.
        yield* step(
          "wait-on-verify-skill-line",
          { returns: Schema.Void },
          Effect.gen(function* () {
            const body = (yield* gh(["issue", "view", issue.number, "--repo", config.repository, "--json", "body", "--jq", ".body"], config.project)).trimEnd();
            yield* gh(["issue", "edit", issue.number, "--repo", config.repository, "--body", `Blocked by: #${blocker}\n\n${body}`], config.project);
          }),
        );
      }
      yield* step("park", { returns: Schema.Void }, store.entry(resumeKey(config, issue), Resume).set({ pr: result.pr, thread: workerThread.threadId }));
      yield* ledger.wrapUp(
        `The skills factory parked this issue until ${verifyIssue} lands, since proving it needs a verify skill. It keeps \`${LABELS.ready}\`, and the factory takes it up again once that issue closes.`,
      );
      return yield* stop(`waiting on ${verifyIssue}`);
    }

    if (result.status !== "DONE") return yield* halt(`the worker returned ${result.status}: ${result.summary}`);
    if (result.pr === null) {
      // No PR means nobody reviewed anything, so the user says whether the issue is done. In
      // needs-triage they see it. Left open with no label, it would block what waits on it unseen.
      yield* step("no-pr", { returns: Schema.Void }, gh(["issue", "edit", issue.number, "--repo", config.repository, "--add-label", LABELS.triage], config.project).pipe(Effect.asVoid));
      yield* ledger.wrapUp(
        `The skills factory finished this issue without a PR, and moved it to \`${LABELS.triage}\`. Close it if you agree that nothing is left to do.\n\n${result.summary}`,
      );
      return { summary: result.summary };
    }

    // ---- The PR's path: green checks, collaborators heard, and a review of the current head.
    // Then the run ends. The PR waits for the user's review with no run open, and a land run
    // merges it once they have said go.
    const pr = issueAddress(config, result.pr);
    const prNumber = String(result.pr).split("/").pop();
    // The factory merges into the repo's default branch, and closes the issue when it does. A PR
    // that goes anywhere else would close the issue with nothing shipped.
    const target = yield* step("target", { returns: Target }, gh(["pr", "view", result.pr, "--json", "baseRefName,url"], config.project).pipe(Effect.map((out) => JSON.parse(out))));
    if (target.baseRefName !== config.defaultBranch || !String(target.url).toLowerCase().includes(`github.com/${config.repository}/pull/`.toLowerCase())) {
      return yield* halt(`its PR, ${result.pr}, does not go into ${config.defaultBranch} of ${config.repository}. The factory merges only a PR that does.`);
    }

    let verdict = null; // { headSha, comment, door, passed }: the review that covers a head.
    let earlier = "none"; // The last verdict comment, for the next reviewer.
    let rulings = "none";
    let rounds = 0;
    let paused = 0; // Waits so far on a repo that was paused while this run was open.
    let go = null; // { head, after }: the head a go must be for, and the label events too old to be one.
    // Ids of comments the worker was given. They are kept in the store, so a later run of this PR
    // does not hand the worker everything that was ever said on it.
    const kept = handledEntry(config, prNumber);
    const handled = [...(yield* step("handled", { returns: Schema.Array(Schema.String) }, kept.get.pipe(Effect.map((found) => (Option.isSome(found) ? found.value : [])))))];
    const keepHandled = (name, ids) => {
      handled.push(...ids);
      return step.try(name, { returns: Schema.Void }, kept.set([...handled]));
    };

    /** Read the PR's head. A new head needs a new go, so a label that was on the PR stops counting. */
    const headNow = Effect.fn(function* (name) {
      go = yield* step(
        name,
        { returns: Go },
        Effect.gen(function* () {
          const detail = yield* pullRequests.read(pr);
          return yield* goFor(config, prNumber, detail.headSha ?? "");
        }),
      );
      return go.head;
    });

    /** Wake the worker on its own thread, and take what it returns. */
    const wake = Effect.fn(function* (name, what) {
      rounds++;
      const woken = yield* agent.try(name, { thread: workerThread, brief: wokeBrief(what), returns: WorkerResult, quiet: "2 hours", timeout: "12 hours" });
      if (woken.outcome === "failed") return yield* halt(`the worker failed after it was woken: ${woken.reason}`);
      ledger.keep(woken.value, { thread: workerThread.threadId, pr: pr.url });
      const settled = yield* answered(woken.value);
      if (settled.status !== "DONE") return yield* halt(`the worker returned ${settled.status}: ${settled.summary}`);
      // The worker may have pushed, and only a push voids the user's go.
      yield* headNow(`${name}-head`);
      return settled;
    });

    /** Start a pass now, so what this run made room for does not wait for the timer. */
    const nextPass = () =>
      step.try(
        "next-pass",
        { returns: Schema.Void },
        Effect.gen(function* () {
          yield* start(dispatch, { scheduledAt: new Date().toISOString(), ending: `${shipOwn(config)}${issue.number}/` }, { key: `pass/${run.id}` });
        }),
      );

    /**
     * Leave the PR to the user's review, and end the run. The store holds what a later look needs:
     * each pass looks at the PR, and a land run merges it once the user has said go. With `auto`
     * the repo merges it without their review, so nothing is announced.
     */
    const handOver = Effect.fn(function* (head, auto, outside, announce) {
      let note = null;
      if (announce) {
        const posted = yield* step.try(
          "ready-note",
          { returns: Schema.String },
          gh(["pr", "comment", pr.url, "--body", readyNote(head, verdict?.passed ?? true, outside)], config.project),
        );
        note = posted.outcome === "failed" ? null : commentId(posted.value);
        // The worker's thread says so too, and stays in the user's list until the PR merges.
        yield* agent.try("ready", { thread: workerThread, brief: readyBrief(pr.url, verdict?.comment ?? null, verdict?.passed ?? true), timeout: "30 minutes" });
      }
      yield* step(
        "ready-record",
        { returns: Schema.Void },
        readyEntry(config, issue.number).set({
          issue,
          pr: pr.url,
          head,
          passed: verdict?.passed ?? true,
          verdict: verdict?.comment ?? null,
          thread: workerThread.threadId,
          auto,
          note,
          shown: outside.map((item) => item.id),
          updatedAt: null,
          lookedAt: null,
          refused: 0,
          byHand: false,
          rework: null,
        }),
      );
      // A land run takes it from here. It merges at once what needs no review, and for a while it
      // looks every minute for the user's go, so a review given right away merges right away.
      yield* step.try(
        "land",
        { returns: Schema.Void },
        Effect.gen(function* () {
          yield* start(land, { config, issue, linger: LINGER }, { key: `${landOwn(config)}${issue.number}/${run.id}` });
        }),
      );
      yield* nextPass();
      yield* ledger.wrapUp(null);
      return { pr: pr.url, ready: head, auto };
    });

    yield* headNow("head-first");
    const told = againBrief(input.again?.why, pr.url, config.defaultBranch);
    if (told !== null) result = yield* wake("again", told);

    for (let pass = 1; ; pass++) {
      if (rounds >= MAX_ROUNDS) return yield* halt(`${pr.url} went round fixes and review ${MAX_ROUNDS} times without landing.`);
      // The settings as they are now, not as they were when the run started. A repo that was
      // paused since gets no more work from its agents until it is on again.
      const now = yield* step(`settings-${pass}`, { returns: Settings }, currentSettings(config));
      if (!now.registered) return yield* halt(`${config.repository} is no longer registered with the factory.`);
      if (!now.enabled) {
        paused++;
        if (paused > MAX_PAUSED_WAITS) return yield* halt(`${config.repository} stayed paused for seven days.`);
        yield* sleep(`paused-${pass}`, "10 minutes");
        continue;
      }
      const at = yield* pullRequests.wait(`checks-${pass}`, pr, { until: "checks", timeout: "3 hours" });
      if (Option.isNone(at)) return yield* halt(`the checks on ${pr.url} were still running after 3 hours.`);
      const standing = at.value;
      // Merged by hand while the run worked on it: a land run does what follows a merge.
      if (standing.state === "merged") return yield* handOver(go.head, false, [], false);
      if (standing.state === "closed") return yield* halt(`${pr.url} was closed outside the factory.`);
      if (standing.checks === "failing" || standing.mergeability === "conflicting") {
        const what = standing.checks === "failing" ? "a check fails on your PR." : "your PR conflicts with main.";
        result = yield* wake(`fix-${pass}`, `${what} PR: ${pr.url}.`);
        continue;
      }

      // A collaborator's comment goes to the worker before anything else, as a request to weigh.
      // Anyone else's comment is data: it never reaches the worker, and never holds the PR. The
      // user is shown it with the PR, and passes on what matters by commenting themselves.
      const said = yield* step(`feedback-${pass}`, { returns: Feedback }, readFeedback(config, pr.url, handled));
      if (said.fresh.length > 0) {
        yield* keepHandled(`heard-${pass}`, said.fresh.map((item) => item.id));
        const list = said.fresh.map((item) => `- ${item.author} (${item.url}): ${item.text}`).join("\n");
        result = yield* wake(
          `feedback-${pass}-fix`,
          `collaborators commented on ${pr.url}. Weigh each one as rules.md says, answer it on the PR, and push what you change.\n\n${list}\n\n`,
        );
        continue;
      }

      const head = yield* headNow(`head-${pass}`);

      if (verdict === null || !sameHead(head, verdict.headSha)) {
        rounds++;
        const review = yield* hire(
          `review-${pass}`,
          {
            project: config.project,
            workspace: worktreeOf(config),
            title: `Reviewer: ${issue.displayKey} ${issue.title}`,
            brief: reviewerBrief(input, verifySkill, pr.url, workerThread.threadId, earlier, rulings),
            returns: Verdict,
            timeout: "8 hours",
          },
          roles.reviewer,
        );
        if (review.outcome === "failed") return yield* halt(`the reviewer failed twice: ${review.reason}`);
        ledger.keep(review.value, { thread: review.thread?.threadId, pr: pr.url });
        const v = review.value;
        if (v.status === "FAILED" || v.headSha === null) return yield* halt(`the reviewer could not reach a verdict: ${v.summary}`);
        earlier = v.comment ?? earlier;
        // The worker may have pushed while the two argued. Seeing the new head at once keeps a go
        // the user gives for it from being taken for an old one.
        const after = yield* headNow(`review-${pass}-head`);
        // The verdict covers the head the reviewer names. A short SHA for the head just read is that head.
        const covered = sameHead(after, v.headSha) ? after : v.headSha;
        if (v.status === "PASS") {
          verdict = { headSha: covered, comment: v.comment, door: v.door, passed: true };
          continue; // Back to the checks, now at the head the verdict names.
        }
        const ruling = yield* askUser(`ruling-${pass}`, {
          title: `${issue.displayKey}: the reviewer and the worker disagree on ${pr.url}`,
          choices: ["accept it as it is", "send my rulings to the worker", "stop"],
          data: { pr: pr.url, head: v.headSha, verdict: v.comment, open: v.open },
          timeout: "7 days",
        });
        if (Option.isNone(ruling)) return yield* halt("nobody ruled on the open findings within 7 days.");
        if (ruling.value.choice === "stop") return yield* halt("the user stopped it at the ruling.");
        if (ruling.value.choice === "accept it as it is") {
          // The open findings stand. The PR still waits for the user's review, like any other.
          verdict = { headSha: covered, comment: v.comment, door: "one-way", passed: false };
          continue;
        }
        rulings = ruling.value.reason?.trim() || "The user sided with the reviewer on every open finding.";
        // No verdict covers the head now, so the next reviewer checks what the worker did with the
        // rulings, whether or not the worker pushed.
        verdict = null;
        result = yield* wake(`rulings-${pass}`, `the user ruled on the reviewer's open findings on ${pr.url}: ${rulings}`);
        continue;
      }

      // Checks are green at the head the verdict covers, and nobody waits on the worker. The run
      // ends here. A PR the repo merges without the user's review is marked so, and nothing is
      // announced for it.
      const auto = verdict.passed && said.held.length === 0 && mayMergeUnasked(now, verdict);
      return yield* handOver(head, auto, said.outside, !auto);
    }
  }),
);

/**
 * A land run acts on one PR that waits for the user's review: it merges it once they have said
 * go, does what follows a merge they made by hand, or hands the PR back when the worker is needed
 * again. It is short. A PR that still waits when it ends is looked at again by each pass.
 */
const land = workflow(
  "skills-factory-land",
  { version: 1, payload: LandInput },
  Effect.fn(function* (input, run) {
    const { config, issue } = input;
    yield* title(`Land ${issue.displayKey} ${issue.title}`);
    const entry = readyEntry(config, issue.number);

    /** Forget the PR: it waits for nobody now. */
    const forget = (ready) =>
      step.try(
        "forget",
        { returns: Schema.Void },
        Effect.gen(function* () {
          const number = ready.pr.split("/").pop();
          yield* entry.delete.pipe(Effect.orElseSucceed(() => undefined));
          yield* goEntry(config, number).delete.pipe(Effect.orElseSucceed(() => undefined));
          yield* handledEntry(config, number).delete.pipe(Effect.orElseSucceed(() => undefined));
        }),
      );

    /** Start a pass now, so what this PR unblocked does not wait for the timer. */
    const nextPass = () =>
      step.try(
        "next-pass",
        { returns: Schema.Void },
        Effect.gen(function* () {
          yield* start(dispatch, { scheduledAt: new Date().toISOString() }, { key: `pass/${run.id}` });
        }),
      );

    /** The worker's thread stayed in the user's list while its PR waited for them. It leaves now. */
    const release = (ready, why) => agent.try("release", { thread: { threadId: ready.thread }, brief: releaseBrief(ready.pr, why), timeout: "15 minutes" });

    /** Do what follows a merge, whoever made it. The next ticket starts before anything that can fail. */
    const finish = Effect.fn(function* (ready, how, asked) {
      const next = yield* step.try("after-merge", { returns: Schema.String }, afterMerge(config, issue, "Its PR merged."));
      yield* forget(ready);
      yield* nextPass();
      if (ready.note !== null) yield* release(ready, "merged");
      if (next.outcome === "failed") {
        yield* step.try(
          "after-merge-note",
          { returns: Schema.Void },
          issues.comment(issueAddress(config, issue.url), `${AI_MARKER}\n\nThe PR merged, but the factory could not check its spec: ${next.reason}`),
        );
      }
      return { pr: ready.pr, merged: how, asked };
    });

    for (let look = 1; ; look++) {
      const ready = yield* step(`record-${look}`, { returns: Schema.NullOr(Ready) }, entry.get.pipe(Effect.map((found) => (Option.isSome(found) ? found.value : null))));
      if (ready === null || ready.rework !== null) return yield* skip("no PR of this issue waits for review");
      const now = yield* step(`settings-${look}`, { returns: Settings }, currentSettings(config));
      // A look that fails is a look that saw nothing: the PR waits, and the next look tries again.
      const looked = yield* step.try(`seen-${look}`, { returns: Seen }, observe(config, ready, now));
      const seen = looked.outcome === "failed" ? null : looked.value;
      const action = seen === null ? { act: "wait" } : decide(ready, seen, now);
      let kept = { ...ready, updatedAt: seen?.updatedAt ?? ready.updatedAt };

      if (action.act === "finish") return yield* finish(ready, "by the user", true);

      if (action.act === "drop") {
        yield* forget(ready);
        yield* step.try(
          "dropped",
          { returns: Schema.Void },
          Effect.gen(function* () {
            yield* gh(["issue", "edit", issue.number, "--repo", config.repository, "--add-label", LABELS.triage], config.project);
            yield* issues.comment(issueAddress(config, issue.url), `${AI_MARKER}\n\nThe skills factory stopped waiting on ${ready.pr}: ${action.why}. It moved this issue to \`${LABELS.triage}\`.`);
          }),
        );
        if (ready.note !== null) yield* release(ready, `will not be merged by the factory: ${action.why}`);
        return { pr: ready.pr, dropped: action.why };
      }

      if (action.act === "rework") {
        // The next pass starts a ship run for it, when the repo has room.
        yield* step(`rework-${look}`, { returns: Schema.Void }, entry.set({ ...kept, rework: action.why }));
        yield* nextPass();
        return { pr: ready.pr, back: action.why };
      }

      if (action.act === "merge") {
        if (seen.draft) yield* step.try(`undraft-${look}`, { returns: Schema.Void }, gh(["pr", "ready", ready.pr], config.project).pipe(Effect.asVoid));
        // `--match-head-commit` makes GitHub refuse the merge if the head moved since the review.
        const merge = yield* step.try(
          `land-${look}`,
          { returns: Schema.Void },
          gh(["pr", "merge", ready.pr, `--${now.mergeMethod}`, "--match-head-commit", ready.head], config.project).pipe(Effect.asVoid),
        );
        if (merge.outcome !== "failed") {
          // A merge queue takes the PR without merging it yet. Nothing that follows a merge
          // happens until GitHub says the PR is in. It mostly is at once, so ask GitHub first.
          const state = yield* step.try(
            `state-${look}`,
            { returns: Schema.String },
            gh(["pr", "view", ready.pr, "--json", "state", "--jq", ".state"], config.project).pipe(Effect.map((out) => out.trim())),
          );
          if (state.outcome === "failed" || state.value !== "MERGED") {
            const inMain = yield* pullRequests.wait(`merged-${look}`, issueAddress(config, ready.pr), { until: "merged", timeout: "6 hours" });
            // Still queued, or closed after all. The PR goes on waiting, and the next pass looks again.
            if (Option.isNone(inMain) || inMain.value.state !== "merged") return yield* skip("GitHub took the merge, and the PR is not merged yet");
          }
          yield* step.try(`delete-branch-${look}`, { returns: Schema.Void }, pullRequests.act(issueAddress(config, ready.pr), "delete-branch"));
          if (ready.auto) {
            const why = "The skills factory merged this without asking: its reviewer passed it as a two-way door, and this repo's settings allow that. Set `autoMerge` to `never` in the factory's settings to be asked every time.";
            yield* step.try(`unasked-${look}`, { returns: Schema.Void }, gh(["pr", "comment", ready.pr, "--body", `${AI_MARKER}\n\n${why}`], config.project).pipe(Effect.asVoid));
          }
          return yield* finish(ready, ready.head, !ready.auto);
        }
        // A refusal may pass: main moved, or GitHub hiccuped. The next look sees why, if GitHub
        // says so. Three in a row is a rule the factory cannot meet, so the user is told.
        kept = { ...kept, refused: ready.refused + 1 };
        if (kept.refused >= 3 && !kept.byHand) {
          yield* step.try(`refused-note-${look}`, { returns: Schema.Void }, gh(["pr", "comment", ready.pr, "--body", byHandNote(merge.reason)], config.project).pipe(Effect.asVoid));
          kept = { ...kept, byHand: true };
        }
      }

      if (action.act === "byHand" && !kept.byHand) {
        yield* step.try(`by-hand-note-${look}`, { returns: Schema.Void }, gh(["pr", "comment", ready.pr, "--body", byHandNote(null)], config.project).pipe(Effect.asVoid));
        kept = { ...kept, byHand: true };
      }

      // The PR waits. A PR that was to merge without the user's review, and cannot any more, is
      // theirs to review after all: tell them, as for any other.
      const outside = seen?.outside ?? [];
      const unlisted = outside.filter((item) => !kept.shown.includes(item.id));
      if (kept.auto && (now.autoMerge !== "two-way" || action.act === "byHand")) {
        const posted = yield* step.try(`ready-note-${look}`, { returns: Schema.String }, gh(["pr", "comment", ready.pr, "--body", readyNote(ready.head, ready.passed, outside)], config.project));
        yield* agent.try(`ready-${look}`, { thread: { threadId: ready.thread }, brief: readyBrief(ready.pr, ready.verdict, ready.passed), timeout: "30 minutes" });
        kept = { ...kept, auto: false, note: posted.outcome === "failed" ? null : commentId(posted.value), shown: outside.map((item) => item.id) };
      } else if (unlisted.length > 0 && kept.note !== null) {
        // What people outside the repo wrote since goes into the note that is there. No new note,
        // and no word in the thread: a stranger's comment is not news the user must act on.
        yield* step.try(
          `note-${look}`,
          { returns: Schema.Void },
          gh(["api", "--method", "PATCH", `repos/${config.repository}/issues/comments/${kept.note}`, "-f", `body=${readyNote(ready.head, ready.passed, outside)}`], config.project).pipe(Effect.asVoid),
        );
        kept = { ...kept, shown: outside.map((item) => item.id) };
      }
      yield* step(
        `keep-${look}`,
        { returns: Schema.Void },
        Effect.gen(function* () {
          yield* entry.set({ ...kept, lookedAt: new Date().toISOString() });
        }),
      );
      if (look > input.linger) return yield* skip("the PR still waits for the user's review");
      yield* sleep(`wait-${look}`, "1 minute");
    }
  }),
);

/** The check of a spec whose tickets have all landed: a reviewer proves its user stories on main. */
const specCheck = workflow(
  "skills-factory-spec",
  {
    version: 8,
    payload: SpecInput,
    // The dispatcher started this check because the spec carried ready-for-agent. Putting the
    // label back checks it again.
    onEnd: (input) =>
      gh(["issue", "edit", input.spec.number, "--repo", input.config.repository, "--remove-label", LABELS.ready], input.config.project),
  },
  Effect.fn(function* (input, run) {
    const { config, spec } = input;
    yield* title(`Spec check: ${spec.displayKey} ${spec.title}`);
    const ledger = ledgerOf(config, run, spec.url);
    const labels = LABELS;
    const again = `Put \`${LABELS.ready}\` on this spec to check it again.`;
    const verifySkill = yield* step("verify-skill", { returns: Schema.NullOr(Schema.String) }, findVerifySkill(config));
    const roles = yield* step("roles", { returns: Roles }, rolesOf(config));

    const check = yield* hire(
      "reviewer",
      {
        project: config.project,
        workspace: worktreeOf(config),
        title: `Spec check: ${spec.displayKey} ${spec.title}`,
        brief: specBrief(input, verifySkill),
        returns: SpecResult,
        timeout: "8 hours",
      },
      roles.reviewer,
    );
    if (check.outcome === "failed") {
      yield* ledger.wrapUp(`The skills factory could not check this spec: the reviewer failed twice: ${check.reason}\n\n${again}`);
      return yield* stop(`the reviewer failed twice: ${check.reason}`);
    }
    const v = check.value;
    ledger.keep(v, { thread: check.thread?.threadId, pr: null });
    if (v.status === "FAILED") {
      yield* ledger.wrapUp(`The skills factory could not check this spec: ${v.summary}\n\n${again}`);
      return yield* stop(`the spec check failed: ${v.summary}`);
    }
    if (v.status === "GAPS" && v.gaps.length === 0) {
      yield* ledger.wrapUp(`The skills factory could not check this spec: the reviewer returned GAPS and named no gap.\n\n${again}`);
      return yield* stop("the spec check returned GAPS with no gap");
    }
    if (v.status === "PASS") {
      yield* ledger.wrapUp(null);
      yield* step("close-spec", { returns: Schema.Void }, gh(["issue", "close", spec.number, "--repo", config.repository], config.project).pipe(Effect.asVoid));
      return { spec: spec.url, result: "PASS", sha: v.sha };
    }

    // Each gap becomes a ticket of the spec, which the factory builds like any other.
    const filed = [];
    for (const [i, gap] of v.gaps.entries()) {
      const url = yield* step(
        `gap-${i + 1}`,
        { returns: Schema.String },
        createIssue(
          config,
          gap.title,
          [
            AI_MARKER,
            "",
            "## Agent Brief",
            "",
            "**Category:** bug",
            "**Route:** bug",
            `**Summary:** A user story of spec #${spec.number} does not hold on main.`,
            "",
            "**Current behavior:**",
            `This user story fails on main: ${gap.story}`,
            "",
            "**Desired behavior:**",
            "The story holds on main.",
            "",
            "**Reproduction:**",
            gap.evidence,
            "",
            "**Acceptance criteria:**",
            "- [ ] The story holds on main, proven on the real surface",
            "",
            "## Parent",
            "",
            `#${spec.number}`,
          ].join("\n"),
          [labels.ready, labels.bug],
          // The spec counts its tickets as its sub-issues, so the gap is one from the start.
          spec.number,
        ),
      );
      filed.push(url);
    }
    yield* ledger.wrapUp(
      `The spec check found ${filed.length} gap(s), each filed as a ticket of this spec:\n\n${filed.map((url) => `- ${url}`).join("\n")}\n\nThe spec closes once they land.`,
    );
    return { spec: spec.url, result: "GAPS", gaps: filed };
  }),
);

/** Start the run of one ready issue, and give its key. Null when the issue is not to start now. */
const startIfReady = (config, issue, number, shipRuns, specRuns) =>
  Effect.gen(function* () {
    const detail = yield* readIssue(config, number);
    // The list trails GitHub by some seconds, so the issue itself says whether it still waits. A
    // PR can carry the label too, and is never work to start.
    if (detail.state !== "open" || detail.pull_request || !detail.labels.some((label) => label.name === LABELS.ready)) return null;
    // A spec in ready-for-agent gets a spec check, once every ticket of it is closed.
    const isSpec = detail.labels.some((label) => label.name === LABELS.spec);
    const own = isSpec ? specOwn(config) : shipOwn(config);
    const tries = triesOf(isSpec ? specRuns : shipRuns, own, number);
    if (tries.some((r) => ACTIVE.includes(r.status))) return null;
    if (isSpec ? !(yield* allTicketsClosed(config, number)) : (yield* openBlockers(config, detail)) > 0) return null;
    const key = `${own}${number}/${yield* nextTry(own, number, tries.length)}`;
    const ref = { number, displayKey: issue.displayKey, title: issue.title, url: issue.url };
    yield* isSpec ? start(specCheck, { config, spec: ref }, { key }) : start(ship, { config, issue: ref }, { key });
    return key;
  });

/**
 * Look at one PR that waits for the user's review, and start a land run for it when something
 * changed: a label, a comment, a commit, a merge or a close by hand. One call to GitHub says
 * whether anything did. A PR nothing touched is looked at in full once in a while all the same.
 */
const lookAtReady = (config, ready, landRuns) =>
  Effect.gen(function* () {
    const number = ready.issue.number;
    if (triesOf(landRuns, landOwn(config), number).some((r) => ACTIVE.includes(r.status))) return null;
    const now = new Date().toISOString();
    const seen = JSON.parse(yield* gh(["pr", "view", ready.pr, "--json", "state,updatedAt"], config.project));
    const due = ready.lookedAt === null || isOlder(ready.lookedAt, now, LOOK_AGAIN_MINUTES);
    if (seen.state === "OPEN" && seen.updatedAt === ready.updatedAt && !due) return null;
    const key = `${landOwn(config)}${number}/${now}`;
    yield* start(land, { config, issue: ready.issue, linger: 0 }, { key });
    return key;
  });

/** One repo's part of a pass: the runs it started, and what it could not do. */
const dispatchRepo = (config, pass) =>
  Effect.gen(function* () {
    const started = [];
    const notes = [];
    const shipRuns = yield* runs({ workflow: ship });
    const specRuns = yield* runs({ workflow: specCheck });
    const landRuns = yield* runs({ workflow: land });

    // PRs that wait for the user's review hold no run and no slot. One that changed gets a land run.
    const waiting = (yield* store.entries(`${PREFIX}/ready/${config.repository}/`, Ready)).map((row) => row.value);
    for (const ready of waiting.filter((row) => row.rework === null)) {
      const key = yield* lookAtReady(config, ready, landRuns).pipe(Effect.orElseSucceed(() => "unreadable"));
      if (key === "unreadable") notes.push(`could not read ${ready.pr}`);
      else if (key !== null) started.push(key);
    }

    // A red main pauses everything but its fix. A failed look at main pauses nothing.
    const fixing = yield* guardMain(config).pipe(Effect.orElseSucceed(() => null));
    if (fixing !== null) notes.push(`main is red in ${config.repository}, so only its fix${fixing === "filing" ? "" : `, #${fixing},`} may start`);
    // The fix may wait on another issue, such as the one that creates the verify skill. That one may start too.
    let allowed = null;
    if (fixing !== null) {
      const fix = fixing === "filing" ? null : yield* readIssue(config, fixing).pipe(Effect.orElseSucceed(() => null));
      allowed = fixing === "filing" ? [] : [fixing, ...blockersInBody(fix?.body)];
    }
    const mine = (r) => r.key?.startsWith(shipOwn(config)) || r.key?.startsWith(specOwn(config));
    let room = config.maxActive - [...shipRuns, ...specRuns].filter((r) => mine(r) && holdsSlot(r, pass)).length;
    // The fix of a red main never waits for a slot, since nothing else may start until it lands.
    if (fixing !== null && fixing !== "filing") room = Math.max(room, 1);

    // A PR that waited for review and needs its worker again comes before new work.
    for (const ready of waiting.filter((row) => row.rework !== null)) {
      if (room <= 0) break;
      const number = ready.issue.number;
      if (allowed !== null && !allowed.includes(number)) continue;
      const tries = triesOf(shipRuns, shipOwn(config), number);
      if (tries.some((r) => ACTIVE.includes(r.status))) continue;
      const key = `${shipOwn(config)}${number}/${yield* nextTry(shipOwn(config), number, tries.length)}`;
      yield* start(ship, { config, issue: ready.issue, again: { thread: ready.thread, pr: ready.pr, why: ready.rework } }, { key });
      started.push(key);
      room--;
    }
    if (room <= 0) return { started, notes };

    const listed = yield* issues.list({ project: config.project, labels: [LABELS.ready], limit: 100 });
    // An issue the pass names is read by its number, which GitHub answers at once. So is the fix
    // of a red main, which this pass may have filed a moment ago.
    const wanted = namedButUnlisted(pass, config.repository, listed);
    if (fixing !== null && fixing !== "filing" && !listed.some((issue) => issueNumber(issue) === fixing) && !wanted.includes(fixing)) wanted.push(fixing);
    const named = [];
    for (const number of wanted) {
      const detail = yield* readIssue(config, number).pipe(Effect.orElseSucceed(() => null));
      const isReady = detail?.state === "open" && !detail.pull_request && detail.labels.some((label) => label.name === LABELS.ready);
      if (isReady) named.push({ displayKey: `#${number}`, title: detail.title, url: detail.html_url, createdAt: detail.created_at });
    }
    // Oldest first, so nothing waits behind newer work for long.
    const queue = [...listed, ...named]
      .sort((a, b) => String(a.createdAt).localeCompare(String(b.createdAt)))
      .filter((issue) => allowed === null || allowed.includes(issueNumber(issue)));
    for (const issue of queue) {
      if (room <= 0) break;
      const number = issueNumber(issue);
      // An issue that cannot be read, or that names a blocker that is not there, skips itself
      // and nothing else.
      const key = yield* startIfReady(config, issue, number, shipRuns, specRuns).pipe(Effect.orElseSucceed(() => "unreadable"));
      if (key === "unreadable") notes.push(`could not read #${number} in ${config.repository}, or an issue it names as a blocker`);
      if (key === null || key === "unreadable") continue;
      started.push(key);
      room--;
    }
    return { started, notes };
  });

const dispatch = workflow(
  "skills-factory-dispatch",
  { version: 6, payload: Pass, triggers: [every("10 minutes")] },
  Effect.fn(function* (pass) {
    const projects = yield* step(
      "projects",
      { returns: Schema.Array(Config) },
      store.entries(`${PREFIX}/projects/`, Config).pipe(Effect.map((rows) => rows.map((row) => row.value))),
    );
    const started = [];
    const notes = [];
    for (const config of projects) {
      if (!config.enabled) continue;
      // One repo's trouble ends that repo's part of the pass, and no other's.
      const done = yield* step.try(`repo ${config.repository}`, { returns: PassResult }, dispatchRepo(config, pass));
      if (done.outcome === "failed") {
        notes.push(`${config.repository}: ${done.reason}`);
        continue;
      }
      started.push(...done.value.started);
      notes.push(...done.value.notes);
    }
    if (started.length === 0) return yield* skip(notes.length > 0 ? cut(notes.join(". "), 300) : "no issue to start");
    return { started, notes };
  }),
);

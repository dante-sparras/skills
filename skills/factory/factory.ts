/**
 * Whether main is red, and the open issue that fixes it. A red main gets one issue in
 * ready-for-agent, filed here, and the dispatcher starts nothing else in the repo until it closes.
 * Returns that issue's number, or null while main is green.
 */
const guardMain = (config) =>
  Effect.gen(function* () {
    const repo = config.repository;
    const cwd = config.project;
    const sha = (yield* gh(["api", `repos/${repo}/commits/${config.defaultBranch}`, "--jq", ".sha"], cwd)).trim();
    const failing = failingChecks(
      yield* ghLines(["api", "--paginate", `repos/${repo}/commits/${sha}/check-runs`, "--jq", ".check_runs[] | {name, status, conclusion, html_url}"], cwd),
      yield* ghLines(["api", `repos/${repo}/commits/${sha}/status`, "--jq", ".statuses[] | {context, state, target_url}"], cwd),
    );
    const entry = store.entry(`${PREFIX}/main-red/${repo}`, MainRed);
    if (failing.length === 0) {
      yield* entry.delete.pipe(Effect.orElseSucceed(() => undefined));
      return null;
    }
    const now = new Date().toISOString();
    const known = yield* entry.get;
    const before = Option.isSome(known) ? known.value : null;
    if (before !== null && before.url !== "") {
      if ((yield* issueState(config, before.url)) === "OPEN") return before.url.split("/").pop();
      // The user closed the fix, and main is red at the same commit. They chose to go on.
      if (before.sha === sha) return null;
    }
    // One pass claims the filing, so two passes at once file one issue. A claim that never
    // became an issue goes stale, and another pass takes it over.
    const token = `${now} ${Math.random().toString(36).slice(2)}`;
    const held = yield* entry
      .update((found) => {
        const old = Option.isSome(found) ? found.value : null;
        const claimed = old !== null && old.url === "" && !isOlder(old.at, now, 10);
        const filed = old !== null && old.url !== "" && old.url !== before?.url;
        return claimed || filed ? old : { url: "", sha, by: token, at: now };
      })
      .pipe(Effect.map((next) => Option.getOrThrow(next)));
    if (held.by !== token) return held.url === "" ? "filing" : held.url.split("/").pop();
    const labels = LABELS;
    const url = yield* createIssue(
      config,
      `Main is red at ${sha.slice(0, 7)}`,
      [
        AI_MARKER,
        "",
        "## Agent Brief",
        "",
        "**Category:** bug",
        "**Route:** bug",
        `**Summary:** These checks fail on main at ${sha}. Make them pass.`,
        "",
        "**Current behavior:**",
        ...failing.map((check) => `- ${check.name}: ${check.url}`),
        "",
        "**Desired behavior:**",
        "Every check on main passes.",
        "",
        "**Acceptance criteria:**",
        "- [ ] Each check above passes on the PR, and on main once it merges",
        "",
        "**Out of scope:**",
        "- Other work. The skills factory starts nothing else in this repo until this issue closes",
      ].join("\n"),
      [labels.ready, labels.bug],
    );
    yield* entry.set({ url, sha, by: token, at: now });
    return url.split("/").pop();
  });


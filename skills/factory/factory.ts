/** What a PR's checks come to. `rollup` is `statusCheckRollup` of `gh pr view`. */
const checksOf = (rollup) => {
  const items = rollup ?? [];
  if (items.length === 0) return "none";
  const red = (item) => RED_CONCLUSIONS.includes(String(item.conclusion ?? "").toLowerCase()) || RED_STATES.includes(String(item.state ?? "").toLowerCase());
  if (items.some(red)) return "failing";
  const pending = (item) => (item.status !== undefined && item.status !== "COMPLETED") || ["PENDING", "EXPECTED"].includes(item.state);
  return items.some(pending) ? "pending" : "passing";
};

/**
 * What to do with a PR that waits for the user's review. `ready` is what the ship run left,
 * `seen` is the PR as it is now, and `settings` are the repo's as they are now.
 * - finish: it is merged, so do what follows a merge.
 * - drop: it will not merge. Give the issue back to the user.
 * - rework: the worker or a reviewer is needed again, and `why` says for what.
 * - merge: the user's go covers this head, and nothing stands in the way.
 * - byHand: the go is there, and GitHub lets only the user merge it.
 * - wait: nothing to do yet.
 */
const decide = (ready, seen, settings) => {
  if (seen.state === "MERGED") return { act: "finish" };
  if (seen.state === "CLOSED") return { act: "drop", why: "its PR was closed" };
  if (!settings.registered) return { act: "drop", why: "the repo is no longer registered with the factory" };
  if (seen.base !== settings.defaultBranch) return { act: "drop", why: `its PR now goes into ${seen.base}, not ${settings.defaultBranch}` };
  if (seen.head !== ready.head) return { act: "rework", why: "commits" };
  if (seen.fresh > 0) return { act: "rework", why: "feedback" };
  if (seen.checks === "failing") return { act: "rework", why: "checks" };
  const go = seen.approved || (ready.auto && settings.autoMerge === "two-way");
  if (!settings.enabled || !go) return { act: "wait" };
  if (seen.merge === "DIRTY") return { act: "rework", why: "conflict" };
  if (seen.merge === "BEHIND") return { act: "rework", why: "behind" };
  if (seen.checks === "pending" || seen.merge === "UNKNOWN") return { act: "wait" };
  if (seen.merge === "BLOCKED") return { act: "byHand" };
  return { act: "merge" };
};


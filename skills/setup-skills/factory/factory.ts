/**
 * Whether main is red, and the open issue that fixes it. A red main gets one issue in
 * ready-for-agent, filed here, and the dispatcher starts nothing else in the repo until it closes.
 * Returns that issue's number, or null while main is green.
 */
const guardMain = (config) =>
  Effect.gen(function* () {
    const repo = config.repository;
    const cwd = config.project;
    const sha = (yield* gh(["api", `repos/${repo}/commits/${config.defaultBranch}`, "--jq", ".sha"], cwd)).trim();
    const failing = failingChecks(
      yield* ghLines(["api", "--paginate", `repos/${repo}/commits/${sha}/check-runs`, "--jq", ".check_runs[] | {name, status, conclusion, html_url}"], cwd),
      yield* ghLines(["api", `repos/${repo}/commits/${sha}/status`, "--jq", ".statuses[] | {context, state, target_url}"], cwd),
    );
    if (failing.length === 0) return null;
    const entry = store.entry(`${PREFIX}/main-red/${repo}`, Schema.String);
    const known = yield* entry.get;
    if (Option.isSome(known) && (yield* issueState(config, known.value)) === "OPEN") return known.value.split("/").pop();
    const labels = LABELS;
    const url = yield* createIssue(
      config,
      `Main is red at ${sha.slice(0, 7)}`,
      [
        AI_MARKER,
        "",
        "## Agent Brief",
        "",
        "**Category:** bug",
        "**Route:** bug",
        `**Summary:** These checks fail on main at ${sha}. Make them pass.`,
        "",
        "**Current behavior:**",
        ...failing.map((check) => `- ${check.name}: ${check.url}`),
        "",
        "**Desired behavior:**",
        "Every check on main passes.",
        "",
        "**Acceptance criteria:**",
        "- [ ] Each check above passes on the PR, and on main once it merges",
        "",
        "**Out of scope:**",
        "- Other work. The skills factory starts nothing else in this repo until this issue closes",
      ].join("\n"),
      [labels.ready, labels.bug],
    );
    yield* entry.set(url);
    return url.split("/").pop();
  });

/** How many of an issue's blockers are open: GitHub's native dependencies, then a `Blocked by` line. */
const openBlockers = (config, issue) =>
  Effect.gen(function* () {
    const native = Number(issue.issue_dependencies_summary?.blocked_by ?? 0);
    if (native > 0) return native;
    let open = 0;
    for (const blocker of blockersInBody(issue.body)) {
      const state = (yield* gh(["api", `repos/${config.repository}/issues/${blocker}`, "--jq", ".state"], config.project)).trim();
      if (state === "open") open++;
    }
    return open;
  });

